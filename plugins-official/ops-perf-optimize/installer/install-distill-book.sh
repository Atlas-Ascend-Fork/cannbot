# Link a local cann-refinery book/ into the installed knowledge repository.
#
# The performance workflow does not clone or update cann-refinery. When the user
# already has a checkout, this standalone initializer links its book/ directory
# to:
#
#   <project>/.cannbot/dependencies/ops-perf-optimize/cannbot-knowledge/distill/book
#
# Analysis reads that link as the distilled knowledge cards. Only book/ is
# linked; yard/ (journal, tools, rough) and law/gate/ stay outside the
# knowledge root.
#
# Usage:
#   bash installer/install-distill-book.sh <project> [refinery-root]
#
# refinery-root defaults to $CANNBOT_REFINERY_ROOT, <project>/cann-refinery, or
# a sibling cann-refinery checkout. The script never downloads anything.

set -euo pipefail

usage() {
  cat >&2 <<'EOF'
Usage: bash installer/install-distill-book.sh <project> [refinery-root]

Links <refinery-root>/book to
<project>/.cannbot/dependencies/ops-perf-optimize/cannbot-knowledge/distill/book.
Install the performance workflow first so the knowledge repository exists.
The script only links an existing checkout; it never clones or updates it.
EOF
}

if [[ "${1:-}" == "--help" || "${1:-}" == "-h" ]]; then
  usage
  exit 0
fi

PROJECT="${1:-${CANNBOT_TARGET_DIR:-}}"
REFINERY="${2:-${CANNBOT_REFINERY_ROOT:-}}"
if [[ -z "$PROJECT" || ! -d "$PROJECT" ]]; then
  usage
  exit 1
fi
PROJECT="$(cd "$PROJECT" && pwd)"

if [[ -z "$REFINERY" ]]; then
  for candidate in \
    "${PROJECT}/cann-refinery" \
    "$(dirname "$PROJECT")/cann-refinery" \
    "${PROJECT}/.cannbot/dependencies/ops-perf-optimize/cann-refinery"; do
    if [[ -d "${candidate}/book/claims" ]]; then
      REFINERY="$candidate"
      break
    fi
  done
fi
if [[ -z "$REFINERY" || ! -d "$REFINERY" ]]; then
  echo "cannbot: cann-refinery checkout not found; pass its path explicitly:" >&2
  echo "  bash installer/install-distill-book.sh ${PROJECT} /path/to/cann-refinery" >&2
  exit 1
fi
REFINERY="$(cd "$REFINERY" && pwd)"
if [[ ! -d "${REFINERY}/book/claims" ]]; then
  echo "cannbot: ${REFINERY} does not look like a cann-refinery checkout (missing book/claims)" >&2
  exit 1
fi

KNOWLEDGE="${PROJECT}/.cannbot/dependencies/ops-perf-optimize/cannbot-knowledge"
if [[ ! -d "$KNOWLEDGE" ]]; then
  echo "cannbot: knowledge repository is missing: ${KNOWLEDGE}" >&2
  echo "cannbot: install the performance workflow first, then rerun this script" >&2
  exit 1
fi

DISTILL="${KNOWLEDGE}/distill"
LINK="${DISTILL}/book"
TARGET="$(cd "${REFINERY}/book" && pwd -P)"
mkdir -p "$DISTILL"

write_config() {
  local config="${PROJECT}/.cannbot/ops-perf-references.env"
  mkdir -p "$(dirname "$config")"
  printf '# Generated by install-distill-book.sh.\nCANNBOT_REFINERY_ROOT=%s\n' "${REFINERY}" > "$config"
}

if [[ -L "$LINK" ]]; then
  CURRENT="$(readlink -f "$LINK" || true)"
  if [[ "$CURRENT" == "$TARGET" ]]; then
    write_config
    echo "distill book: ready ${LINK} -> ${TARGET}"
    exit 0
  fi
  rm -f "$LINK"
elif [[ -e "$LINK" ]]; then
  echo "cannbot: ${LINK} exists and is not a symlink; refusing to replace it" >&2
  exit 1
fi

ln -s "$TARGET" "$LINK"
write_config
echo "distill book: linked ${LINK} -> ${TARGET}"

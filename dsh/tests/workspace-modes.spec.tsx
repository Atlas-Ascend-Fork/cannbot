function observable<T>(value: T) {
  const listeners = new Set<() => void>()
  return { getSnapshot: () => value, subscribe(listener: () => void) { listeners.add(listener); return () => { listeners.delete(listener) } }, set(next: T) { value = next; for (const listener of listeners) listener() } }
}
const workspace = (id: string, sharedWithDeepSeek = false) => ({ workspaceId: id, path: '/' + id, title: id, pluginId: 'ops-direct-invoke', sessionIds: ['C-' + id], sharedWithDeepSeek })
function fixture() {
  let navigation = new AbortController()
  const sessions = observable({ phase: 'ready' as 'ready' | 'pending', current: 'D1', byId: { D1: { title: '旧对话', retainedBy: { mainView: 1 } }, 'C-W': { title: 'CANN对话', retainedBy: {} } } })
  const panelInfo = observable({ activePanelId: null as string | null })
  const ctx = {
    sessions: { list: sessions, create: vi.fn(), retain: vi.fn((id: string) => ({ ready: Promise.resolve({ sessionId: id }), release: vi.fn() })) },
    layout: { panelInfo, selectPanel: vi.fn((activePanelId: string | null) => panelInfo.set({ activePanelId })), beginNavigation: vi.fn(() => { navigation.abort(); navigation = new AbortController(); return navigation.signal }) },
    uiWorkspace: { openSession: vi.fn((id: string) => { sessions.set({ ...sessions.getSnapshot(), current: id }); panelInfo.set({ activePanelId: null }) }), startSession: vi.fn() },
  } as unknown as Context
  let tree = { mode: 'cannbot', workspaces: [workspace('W')], sessions: [{ sessionId: 'C-W', workspaceId: 'W', pluginId: 'ops-direct-invoke', title: 'CANN对话' }] }
  const fetch = vi.fn(async (_: unknown, init?: RequestInit) => {
    if (init?.method === 'POST') {
      const body = JSON.parse(init.body as string)
      if (body.action === 'create') { const created = { ...workspace('NEW'), path: body.path, pluginId: body.pluginId, sessionIds: [] }; tree = { ...tree, workspaces: [...tree.workspaces, created] }; return new Response(JSON.stringify({ workspace: created })) }
      const session = { sessionId: body.sessionId, workspaceId: body.workspaceId, pluginId: 'ops-direct-invoke', title: '' }
      tree = { ...tree, sessions: [...tree.sessions, session], workspaces: tree.workspaces.map(item => item.workspaceId === body.workspaceId ? { ...item, sessionIds: [...item.sessionIds, body.sessionId] } : item) }
      return new Response(JSON.stringify({ ok: true, session }))
    }
    return new Response(JSON.stringify(tree))
  })
  vi.stubGlobal('fetch', fetch)
  const modes = createWorkspaceModes(ctx)
  return { modes, ctx, fetch, sessions, panelInfo }
}

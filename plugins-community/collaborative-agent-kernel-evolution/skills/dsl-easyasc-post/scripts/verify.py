"""verify.py — final post-skill verification of `<Op>Custom/`.

Runs after `rebuild_if_modified.sh` to confirm the produced .run package and
shared libraries actually export the renamed op-class symbols. This is the
final guard before handing off to ascend-evaluation.

Checks:
  1. {Op}Custom/build_out/custom_opp_*.run exists.
  2. {Op}Custom/build_out/op_api/lib/libcust_opapi.so OR equivalent exists.
  3. nm -D on the .so reports a symbol whose mangled form contains the snake-case
     entry, e.g. `flash_attention_custom`.
  4. The aclnn header `aclnn_*.h` was emitted with the snake-case op name (this is
     what cake's PyBind layer #includes).
  5. diff_layout.py --mode post is green.

Usage:
    python verify.py <op_name> [--output-root ./output]

Exit codes:
  0 ok
  1 verification failure
  2 setup error
"""

from __future__ import annotations

import argparse
import json
import logging
import shutil
import subprocess
import sys
from pathlib import Path


class _StreamProxy:
    """按名字在写出时解析 sys.stdout / sys.stderr。

    logging.StreamHandler 在构造时就持有流对象，而 print 每次调用才取
    sys.stdout / sys.stderr。用本代理转发，使二者行为一致——进程内替换或
    重定向标准流时，输出仍落到替换后的流。
    """

    def __init__(self, name: str) -> None:
        self._name = name

    def write(self, text: str) -> int:
        return getattr(sys, self._name).write(text)

    def flush(self) -> None:
        getattr(sys, self._name).flush()


_LOG = logging.getLogger(__name__ + ".stdout")
_ERR = logging.getLogger(__name__ + ".stderr")


def _init_loggers() -> None:
    """把脚本输出接到 logging，格式为 %(message)s，每行内容与原 print 一致。"""
    for logger, name in ((_LOG, "stdout"), (_ERR, "stderr")):
        if logger.handlers:
            continue
        handler = logging.StreamHandler(_StreamProxy(name))
        handler.setFormatter(logging.Formatter("%(message)s"))
        logger.addHandler(handler)
        logger.setLevel(logging.INFO)
        logger.propagate = False


_init_loggers()


def snake_to_pascal(snake: str) -> str:
    return "".join(part.capitalize() for part in snake.split("_") if part)


def find_run(dst: Path):
    candidates = sorted(dst.glob("build_out/custom_opp_*.run"))
    return candidates[0] if candidates else None


def find_aclnn_header(dst: Path, snake: str):
    # cake's CMake installs autogenerated aclnn_<op>.h under build_out/autogen.
    candidates = list(dst.glob(f"build_out/autogen/aclnn_*{snake}*.h")) + list(
        dst.glob(f"build_out/**/aclnn_*{snake}*.h")
    )
    return candidates[0] if candidates else None


def nm_lookup(so_path: Path, *needles: str) -> bool:
    """Return True if any exported symbol contains any of the needles."""
    nm = shutil.which("nm")
    if not nm:
        return True  # can't check; don't fail.
    try:
        out = subprocess.check_output(
            [nm, "-D", "--defined-only", str(so_path)], stderr=subprocess.DEVNULL
        ).decode("utf-8", "replace")
    except subprocess.CalledProcessError:
        return False
    return any(n in line for line in out.splitlines() for n in needles)


CUBE_OPS = ("BlockMmad", "blockMmad", "Mmad", "mmad", "MMAD", "matmul(")


def check_build_artifacts(dst: Path, snake: str, op_pascal: str):
    """检查 1-4：.run 包、opapi .so 与其符号、aclnn 头。

    返回 (run 包路径或 None, 失败说明列表)。aclnn 头缺失只告警不计失败。
    """
    failures = []
    # 1. .run
    run = find_run(dst)
    if run is None:
        failures.append(f"missing .run package under {dst}/build_out/")
    else:
        _LOG.info(f"[verify] run_package: {run}")

    # 2. opapi .so
    opapi = None
    for cand in dst.glob("build_out/**/libcust_opapi*.so"):
        opapi = cand
        break
    if opapi is None:
        failures.append("missing libcust_opapi*.so under build_out/")
    else:
        _LOG.info(f"[verify] opapi_so: {opapi}")
        # 3. nm symbol contains snake-case entry OR aclnn{Op}Custom
        if not nm_lookup(opapi, snake, f"aclnn{op_pascal}Custom"):
            failures.append(
                f"nm -D on {opapi} reports no symbol containing "
                f"{snake!r} or 'aclnn{op_pascal}Custom'"
            )

    # 4. aclnn header
    hdr = find_aclnn_header(dst, snake)
    if hdr is None:
        # aclnn header is a soft signal — ascend-evaluation's PyBind reaches for the
        # registered op-class name via aclnn dispatch, not the header. Warn only.
        _ERR.info(
            f"[verify] WARN: no aclnn_*{snake}*.h found; ascend-evaluation may still work via aclnn dispatch"
        )
    else:
        _LOG.info(f"[verify] aclnn_header: {hdr}")
    return run, failures


def warn_residual_pipe_barrier(dst: Path, snake: str) -> None:
    """检查 6：vec-only 算子若残留 PipeBarrier<PIPE_ALL>() 则告警。"""
    kernel_cpp = dst / f"op_kernel/{snake}_custom.cpp"
    cube_h = dst / "op_kernel/kernel_cube.h"
    if kernel_cpp.exists():
        kernel_text = kernel_cpp.read_text()
        cube_text = cube_h.read_text() if cube_h.exists() else ""
        cube_has_ops = any(op in cube_text for op in CUBE_OPS)
        if not cube_has_ops and "PipeBarrier<PIPE_ALL>()" in kernel_text:
            # 对于 vec-only 算子（cube 侧无 BlockMmad），PIPE_ALL 包含 PIPE_FIX，
            # AIV 侧会等待 AIC 侧的 BlockMmad 信号，但 AIC 路径为空，永远不会发出信号
            # → kernel 挂起，输出全零。这是 easyasc codegen 的自动插入行为，
            # transform.py Step B 应已自动移除，若此处仍出现说明需重跑 transform。
            _ERR.info(
                f"[verify] WARN: {snake}_custom.cpp contains PipeBarrier<PIPE_ALL>() "
                f"but kernel_cube.h has no Cube ops (BlockMmad/Mmad/matmul). "
                f"On vec-only kernels this causes AIV to deadlock (output will be all zeros). "
                f"Re-run: python transform.py {snake} --force  to auto-remove it."
            )


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("op_name")
    ap.add_argument("--output-root", default="./output")
    args = ap.parse_args()

    out_root = Path(args.output_root).resolve()
    snake = args.op_name
    op_pascal = snake_to_pascal(snake)
    dst = out_root / snake / f"{op_pascal}Custom"
    ws = out_root / snake / "easyasc_workspace"
    status_path = ws / "codegen_status.json"

    if not dst.is_dir():
        _ERR.info(f"[verify] ERROR: destination {dst} missing")
        return 2

    run, failures = check_build_artifacts(dst, snake, op_pascal)

    # 5. diff_layout post
    here = Path(__file__).resolve().parent
    rc = subprocess.call(
        [
            sys.executable,
            str(here / "diff_layout.py"),
            snake,
            "--mode",
            "post",
            "--output-root",
            str(out_root),
        ]
    )
    if rc != 0:
        failures.append("diff_layout.py --mode post failed")

    warn_residual_pipe_barrier(dst, snake)

    if failures:
        for f in failures:
            _ERR.info(f"[verify] FAIL: {f}")
        if status_path.is_file():
            s = json.loads(status_path.read_text())
            s["next_step"] = "human-intervention"
            status_path.write_text(json.dumps(s, indent=2))
        return 1

    _LOG.info(f"[verify] PASS dst={dst} run_package={run}")
    if status_path.is_file():
        s = json.loads(status_path.read_text())
        s["next_step"] = "ascend-evaluation"
        s.setdefault("post", {})["verified"] = True
        status_path.write_text(json.dumps(s, indent=2))
    return 0


if __name__ == "__main__":
    sys.exit(main())

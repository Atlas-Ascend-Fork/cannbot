# init_workspace.sh — create easyasc workspace under output/{op}/easyasc_workspace/.
#
# Usage:
#   bash init_workspace.sh <op_name> <target> [<output_root>]
#
# Args:
#   op_name      e.g. flash_attention
#   target       a2 | a5
#   output_root  defaults to ./output (relative to current working dir)
#
# Side effects:
#   - mkdir -p <output_root>/<op>/easyasc_workspace/
#   - writes env.sh with PYTHONPATH (easyasc repo) + ASCEND_HOME_PATH passthrough
#   - seeds codegen_status.json with target_device + op_name
#
# The script does NOT overwrite an existing codegen_status.json that already has
# completed fields; it only seeds when the file is missing.

set -eu

OP_NAME="${1:-}"
TARGET="${2:-}"
OUTPUT_ROOT="${3:-./output}"

if [ -z "$OP_NAME" ] || [ -z "$TARGET" ]; then
  echo "usage: $0 <op_name> <target a2|a5> [output_root]" >&2
  exit 1
fi

if [ "$TARGET" != "a2" ] && [ "$TARGET" != "a5" ]; then
  echo "target must be a2 or a5, got: $TARGET" >&2
  exit 1
fi

# The easyasc library is not distributed with this plugin. EASYASC_DSL_HOME is the
# contract documented in docs/EXTERNAL_DEPENDENCIES.md; do not guess a path.
EASYASC_REPO="${EASYASC_DSL_HOME:-}"
if [ -z "$EASYASC_REPO" ]; then
  echo "EASYASC_DSL_HOME is not set — point it at your easyasc checkout" >&2
  echo "  (the directory containing easyasc/; see docs/EXTERNAL_DEPENDENCIES.md)" >&2
  exit 1
fi
if [ ! -d "$EASYASC_REPO/easyasc" ]; then
  echo "no easyasc/ under EASYASC_DSL_HOME=$EASYASC_REPO;" >&2
  echo "  run 'bash agent/scripts/init.sh' in that checkout first" >&2
  exit 1
fi

WS="$OUTPUT_ROOT/$OP_NAME/easyasc_workspace"
mkdir -p "$WS"

# env.sh — sourced by run_smoke.py / run_codegen.py wrappers.
cat > "$WS/env.sh" <<EOF
# Generated by dsl-easyasc-codegen/scripts/init_workspace.sh
# Source this before running OpExec scripts.

export PYTHONPATH="${EASYASC_REPO}:\${PYTHONPATH:-}"

# ASCEND_HOME_PATH must already be exported by the user; we only check it.
if [ -z "\${ASCEND_HOME_PATH:-}" ]; then
  echo "WARNING: ASCEND_HOME_PATH is not set — OpExec(simulator=False) will fail" >&2
fi

# Avoid set -u tripping over ASCEND_CUSTOM_OPP_PATH inside CANN scripts.
: "\${ASCEND_CUSTOM_OPP_PATH:=}"
export ASCEND_CUSTOM_OPP_PATH
EOF

# codegen_status.json — seed only if missing.
STATUS="$WS/codegen_status.json"
if [ ! -f "$STATUS" ]; then
  cat > "$STATUS" <<EOF
{
  "op_name": "$OP_NAME",
  "target_device": "$TARGET",
  "device_check": {
    "passed": null,
    "host_device": null,
    "warnings": []
  },
  "smoke": {
    "passed": null,
    "attempts": 0
  },
  "ascendc_generated": false,
  "raw_dir": null,
  "run_package": null,
  "aclnn_test_dir": null,
  "next_step": null
}
EOF
fi

# Echo workspace path for the caller / SKILL.md to capture.
echo "$WS"

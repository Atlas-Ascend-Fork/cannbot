def _annotation_id(ann: ast.expr) -> str:
    """Return the simple type name of a parameter annotation, e.g. 'GMTensor'."""
    if isinstance(ann, ast.Name):
        return ann.id
    # Subscripts like `Optional[GMTensor]` are not supported in v1.
    return ast.unparse(ann) if hasattr(ast, "unparse") else "?"


def _is_kernel_decorator(dec: ast.expr) -> bool:
    """Return True if the decorator looks like `@kernel()` or `@kernel`."""
    if isinstance(dec, ast.Call) and isinstance(dec.func, ast.Name):
        return dec.func.id == "kernel"
    if isinstance(dec, ast.Name):
        return dec.id == "kernel"
    return False


def _collect_lshift_lhs_targets(fn: ast.FunctionDef) -> set:
    """Scan the function body for `target <<= ...` statements (and similar
    annotated/aug-assignment forms used by easyasc's `<<=` data-move operator).
    Return the set of root identifiers that appear on the LHS — these are the
    GMTensor params being written to (i.e., outputs).

    Catches:
      quantized[r*N:r*N+N] <<= q_int8       → "quantized"
      scale[r:r+1] <<= scale_bf16           → "scale"
      out <<= x[...]                         → "out"
    """
    targets: set = set()

    def root_name(expr: ast.expr) -> str | None:
        # Unwrap Subscripts (foo[i] → foo) and Attributes (foo.bar → foo)
        while isinstance(expr, (ast.Subscript, ast.Attribute)):
            expr = expr.value
        if isinstance(expr, ast.Name):
            return expr.id
        return None

    for node in ast.walk(fn):
        # `target <<= value`  → AugAssign with op=LShift
        if isinstance(node, ast.AugAssign) and isinstance(node.op, ast.LShift):
            r = root_name(node.target)
            if r is not None:
                targets.add(r)
    return targets


def parse_dsl_signature(dsl_path: Path, expected_name: str):
    """Find the @kernel-decorated function and extract its parameter list.

    Returns:
      params:        list of (param_name, annotation_type)  e.g. [("x", "GMTensor"), ("M", "Var")]
      var_names:     subset of params with annotation=="Var", in order
      output_names:  subset of GMTensor params that appear as LHS of `<<=`

    Raises ValueError on unsupported patterns (missing decorator, wrong name,
    GMTensor after Var, etc.)
    """
    try:
        tree = ast.parse(dsl_path.read_text(encoding="utf-8"), filename=str(dsl_path))
    except SyntaxError as exc:
        raise ValueError(f"failed to parse {dsl_path}: {exc}") from exc

    target_fn = None
    for node in tree.body:
        if isinstance(node, ast.FunctionDef) and node.name == expected_name:
            if any(_is_kernel_decorator(d) for d in node.decorator_list):
                target_fn = node
                break

    if target_fn is None:
        raise ValueError(
            f"no top-level function `{expected_name}` decorated with @kernel() "
            f"found in {dsl_path}"
        )

    if target_fn.args.vararg or target_fn.args.kwonlyargs or target_fn.args.kwarg:
        raise ValueError(
            f"kernel `{expected_name}` has *args / **kwargs / kw-only params; "
            "only positional arguments are supported"
        )

    params: List[Tuple[str, str]] = []
    seen_var = False
    for arg in target_fn.args.args:
        if arg.annotation is None:
            raise ValueError(
                f"kernel parameter `{arg.arg}` has no type annotation; "
                "expected `GMTensor` or `Var`"
            )
        ann = _annotation_id(arg.annotation)
        if ann not in {"GMTensor", "Var"}:
            raise ValueError(
                f"unsupported parameter annotation `{ann}` on `{arg.arg}`; "
                "expected `GMTensor` or `Var`"
            )
        if ann == "Var":
            seen_var = True
        elif ann == "GMTensor" and seen_var:
            raise ValueError(
                f"GMTensor parameter `{arg.arg}` follows a Var; "
                "easyasc requires GMTensor params to come before Vars"
            )
        params.append((arg.arg, ann))

    var_names = [n for n, t in params if t == "Var"]
    output_names = _collect_lshift_lhs_targets(target_fn)
    # Filter to GMTensor params only (loop iterators / local UB tensors don't count)
    gm_param_names = {n for n, t in params if t == "GMTensor"}
    output_names &= gm_param_names
    return params, var_names, output_names



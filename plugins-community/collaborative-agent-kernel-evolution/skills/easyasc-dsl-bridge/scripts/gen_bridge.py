def render_cpp(
    op_name: str,
    inputs: List[Tuple[str, str]],
    outputs: List[Tuple[str, str]],
    scalar_assignments: List[Tuple[str, str, str]],
    *,
    aclnn_call_sequence: List[Tuple[str, str, str]],
    out_shape_exprs: List[str],
    in_dsl_dtypes: List[str] | None = None,
    out_dsl_dtypes: List[str] | None = None,
    pybind_attrs: List[Tuple[str, str, str]] | None = None,
) -> str:
    """Render the bridge cpp.

    Parameter ordering for the C call (typedef + invocation) comes entirely
    from ``aclnn_call_sequence`` — the parsed aclnn header. ``inputs`` /
    ``outputs`` / ``scalar_assignments`` are still used for tensor allocation,
    output shape expressions, and scalar-value derivation respectively.

    Optional ``in_dsl_dtypes``/``out_dsl_dtypes`` — if provided AND any entry
    differs from the corresponding op_desc dtype — inject ``bf16↔fp32`` (or
    any pair) cast layer so the DSL kernel sees its expected dtype while the
    caller-visible signature keeps the op_desc dtype.

    Optional ``pybind_attrs`` — list of ``(name, c_type, py_default)`` for
    attributes marked ``"@pybind:<default>"`` in op_desc. Each becomes an
    extra parameter in the C++ function signature and the pybind binding's
    Python signature (with the given default), instead of being baked as a
    local variable. Useful for runtime-configurable values like epsilon.
    """
    pybind_attrs = pybind_attrs or []

    # ── DSL-vs-op_desc dtype mismatch detection ────────────────────────────
    # For each input/output, decide whether we need a cast and which name the
    # aclTensor should be built from. Default (no mismatch): use the caller
    # tensor name and op_desc dtype. With mismatch: introduce a cast alias
    # `{name}_dsl` (or `{name}_out_dsl` for outputs) that the aclTensor uses.
    sig = _render_signature_parts(
        aclnn_call_sequence,
        inputs,
        outputs,
        pybind_attrs,
        in_dsl_dtypes=in_dsl_dtypes,
        out_dsl_dtypes=out_dsl_dtypes,
    )

    # ── per-tensor "effective name" used by aclTensor + first_input options ──
    # When DSL dtype matches op_desc dtype: effective_name == caller's name.
    # When mismatched: effective_name == "{name}_dsl" (cast alias) and we
    # emit `at::Tensor {name}_dsl = ({name}.scalar_type() == ...) ? ... : ...;`
    # earlier in the function.
    dsl_dt, in_effective_names, input_dsl_casts_block, name = (
        _render_input_effective_names(sig.in_dsl_dtypes, inputs)
    )

    # ── output tensor allocations ─────────────────────────────────────────
    # Two-track allocation when there's a mismatch:
    #   1. Allocate {out_name}_out_dsl with the DSL dtype (kernel writes here)
    #   2. After kernel completes, cast back: {out_name} = {out_name}_out_dsl.to(api dtype)
    # When no mismatch: single allocation, use caller's name directly.
    (dsl_dt, out_effective_names, output_allocations, output_post_casts_block) = (
        _render_output_allocations(
            sig.first_input, sig.out_dsl_dtypes, out_shape_exprs, outputs
        )
    )

    # ── scalar assignments  (each: <c_type> <name> = <expr>;) ────────────
    scalar_lines: List[str] = []
    for var_name, c_type, init_expr in scalar_assignments:
        scalar_lines.append(f"    {c_type} {var_name} = {init_expr};")
    scalar_assignments_block = "\n".join(scalar_lines)

    # ── aclTensor creates ─────────────────────────────────────────────────
    # Use effective names (cast aliases) and DSL dtypes here — the kernel
    # expects the DSL dtype, regardless of the user-visible api dtype.
    cast = _render_cast_and_pybind_parts(
        aclnn_call_sequence,
        sig.in_dsl_dtypes,
        in_effective_names,
        input_dsl_casts_block,
        inputs=inputs,
        out_dsl_dtypes=sig.out_dsl_dtypes,
        out_effective_names=out_effective_names,
        output_post_casts_block=output_post_casts_block,
        outputs=outputs,
        pybind_attrs=pybind_attrs,
    )

    return _emit_cpp(op_name, sig, cast, output_allocations, scalar_assignments_block)



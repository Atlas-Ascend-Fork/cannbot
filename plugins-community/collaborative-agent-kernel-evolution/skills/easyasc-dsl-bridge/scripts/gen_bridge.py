"""Generate a torch_npu pybind cpp ("bridge") for an easyasc-codegen kernel.

Reads:
  - output/<op_name>/<op_name>_dsl.py        (DSL with @kernel() def <op_name>_custom)
  - output/<op_name>/<op_name>_op_desc.json  (input/output dtype declarations)
  - output/<op_name>/easyasc_workspace/<op_name>_raw/build_out/autogen/
        aclnn_*.h                            (autogenerated by easyasc-codegen;
                                              SOURCE OF TRUTH for parameter
                                              ordering and C types)

Writes:
  - output/<op_name>/<op_name>.cpp           (overwrites any prior file)
  - output/<op_name>/<op_name>_custom.py     (ModelNew skeleton — preserved if present)

The generated cpp uses easyasc-style EXECOP dispatch (dlopen libcust_opapi.so +
libnnopbase.so, c10_npu::NPUGuard, current torch_npu stream, raw aclrtMalloc with
HUGE_FIRST). This bypasses CAKE's pytorch_npu_helper.hpp::EXEC_NPU_CMD which is
incompatible with easyasc-codegen output (triggers aicore exception 507015).

Design note — why this runs AFTER easyasc-codegen
--------------------------------------------------
Earlier versions parsed only the DSL AST and assumed easyasc-codegen would
emit ``aclnn{Op}CustomGetWorkspaceSize`` with the layout
``inputs..., scalars..., outputs..., ws*, exec**``. That assumption is
**brittle** — easyasc's codegen rule for scalar/output interleaving can vary
by op family (multi-output, cube, attribute-baked Vars, etc.) and silent
mismatches produce wrong outputs with no compile error.

The bridge now runs as cake stage 6 (after easyasc-codegen in stage 5)
so it can parse the **autogenerated** ``aclnn_{snake}_custom.h`` and use that
as the ground truth for both (a) the C-type of every parameter and (b) the
positional order in the call to ``g_get_ws``. The DSL AST is still consulted
for input/output classification (via ``<<=`` analysis), Var → dim-alias
mapping, output shape inference, and dtype cast detection — but it never
decides the ordering.

See ../SKILL.md for the full design rationale and the v2.1 changelog.
"""


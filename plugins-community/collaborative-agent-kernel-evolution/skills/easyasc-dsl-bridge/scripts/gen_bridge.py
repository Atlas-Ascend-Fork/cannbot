def split_io_tensors(
    params: List[Tuple[str, str]],
    output_names: set,
    op_desc: dict,
):
    """Split GMTensor params into (inputs, outputs) using `<<=` LHS analysis
    (preferred) plus op_desc dtypes (truth source).

    The DSL's GMTensor list is the kernel-level signature, which may include
    *more* tensors than `op_desc.shape_info.input_shapes` declares — e.g.
    dynamic_quant's `smooth_scales` is held inside the PyTorch model as an
    nn.Parameter, so it doesn't show up in op_desc inputs, but it IS a kernel
    input. We use AST scanning of `<<=` to determine which GMTensor params
    are actually written, and treat the rest as inputs.

    Dtypes are resolved by name against `op_desc.shape_info` first, falling
    back to the *first* declared dtype if the param name isn't in op_desc.

    Returns:
      inputs:  list of (param_name, dtype_str)  — order matches DSL signature
      outputs: list of (param_name, dtype_str)  — order matches DSL signature
    """
    tensor_params = [n for n, t in params if t == "GMTensor"]
    if not tensor_params:
        raise ValueError("kernel has no GMTensor parameters")

    if not output_names:
        raise ValueError(
            "no GMTensor parameter is written to via `<<=`; cannot detect outputs. "
            "easyasc DSL outputs must be assigned via the `<<=` operator at least once."
        )

    in_decls = op_desc.get("shape_info", {}).get("input_shapes") or []
    out_decls = op_desc.get("shape_info", {}).get("output_shapes") or []
    if not in_decls or not out_decls:
        raise ValueError(
            "op_desc.json must declare both input_shapes and output_shapes"
        )

    # Build lookup: param-name → dtype  (search both input_shapes and output_shapes by name)
    name_to_dtype: dict = {}
    for decl in in_decls + out_decls:
        if decl.get("name") and decl.get("dtype"):
            name_to_dtype[decl["name"]] = decl["dtype"]

    def resolve_dtype(param_name: str, is_output: bool) -> str:
        # Prefer exact name match
        if param_name in name_to_dtype:
            return name_to_dtype[param_name]
        # Fallback: first input/output dtype declared in op_desc (covers params
        # that are kernel-level only, e.g. nn.Parameter-style smooth_scales).
        decls = out_decls if is_output else in_decls
        return decls[0].get("dtype")

    inputs: List[Tuple[str, str]] = []
    outputs: List[Tuple[str, str]] = []
    for name in tensor_params:
        is_out = name in output_names
        dtype = resolve_dtype(name, is_output=is_out)
        if dtype not in DTYPE_TO_ACL:
            raise ValueError(
                f"GMTensor `{name}` has unsupported dtype `{dtype}`; "
                f"supported: {sorted(DTYPE_TO_ACL)}"
            )
        if is_out:
            outputs.append((name, dtype))
        else:
            inputs.append((name, dtype))

    if len(outputs) != len(out_decls):
        raise ValueError(
            f"detected {len(outputs)} outputs from DSL ({[n for n, _ in outputs]}) "
            f"but op_desc declares {len(out_decls)} output_shapes; "
            "make sure op_desc.shape_info.output_shapes lists every kernel output."
        )

    return inputs, outputs


def _infer_two_input_shape_expr(
    out_shape,
    in0_shape,
    in0_dsl_name,
    in_decls: List[dict],
    inputs_dsl: List[Tuple[str, str]],
) -> str | None:
    """模式 3-4：需要第二个输入才能推导的输出形状，推不出时返回 None。"""
    in1_decl = in_decls[1]
    in1_shape = list(in1_decl.get("shape", []))
    in1_dsl_name = inputs_dsl[1][0]

    # ----- Pattern 3: matmul (M,K)@(K,N) -> (M,N), generalized to broadcast on leading dims of input[0] -----
    if (
        len(in0_shape) >= 2
        and len(in1_shape) >= 1
        and out_shape == in0_shape[:-1] + [in1_shape[-1]]
    ):
        return (
            f"[&]{{ "
            f"auto __s = {in0_dsl_name}.sizes().vec(); "
            f"__s.back() = {in1_dsl_name}.size(-1); "
            f"return __s; "
            f"}}()"
        )

    # ----- Pattern 4: batched matmul / QK^T -----
    if (
        len(in0_shape) >= 2
        and len(in1_shape) >= 1
        and out_shape == in0_shape[:-1] + [in1_shape[-1]]
    ):
        # already handled by pattern 3
        pass
    if (
        len(in0_shape) >= 2
        and len(in1_shape) >= 1
        and out_shape == in0_shape[:-2] + [in0_shape[-2], in1_shape[-1]]
    ):
        return (
            f"[&]{{ "
            f"auto __s = {in0_dsl_name}.sizes().vec(); "
            f"__s.back() = {in1_dsl_name}.size(-1); "
            f"return __s; "
            f"}}()"
        )

    # ----- Pattern 6: nn.Linear-style transposed weight matmul -----
    # x @ weight.T where x = (..., K), weight = (N, K). Out = (..., N).
    # The kernel takes weight as the second GMTensor in (N, K) layout
    # (matches easyasc.a5 cube tiling convention).
    if (
        len(in0_shape) >= 2
        and len(in1_shape) >= 2
        and out_shape == in0_shape[:-1] + [in1_shape[-2]]
    ):
        return (
            f"[&]{{ "
            f"auto __s = {in0_dsl_name}.sizes().vec(); "
            f"__s.back() = {in1_dsl_name}.size(-2); "
            f"return __s; "
            f"}}()"
        )
    return None


def infer_output_shape_expr(
    out_decl: dict,
    in_decls: List[dict],
    inputs_dsl: List[Tuple[str, str]],
) -> str:
    """Return a C++ expression that produces a `std::vector<int64_t>` for the
    output's shape, in terms of the input at::Tensor variables.

    Supported patterns (checked in order):
      1. output.shape == input[0].shape
         → `<in0>.sizes().vec()`
         e.g. elementwise / norm.
      2. output.shape == input[0].shape[:-1]
         → input shape minus last dim.
         e.g. reduce-over-last-dim, dynamic-quant scale.
      3. output.shape == input[0].shape[:-1] + [input[1].shape[-1]]
         → matmul: (M,K) @ (K,N) -> (M,N) / (B,S,K)@(K,N)->(B,S,N).
      4. output.shape == input[0].shape[:-2] + [input[0].shape[-2], input[1].shape[-1]]
         → batched matmul / attention QK^T:
           (B,H,S,K)@(B,H,K,T) -> (B,H,S,T).
      6. output.shape == input[0].shape[:-1] + [input[1].shape[-2]]
         → transposed-weight matmul (nn.Linear convention):
           x @ weight.T where x is (M,K) and weight is (N,K). Output (M,N).
           Also handles batched cases: (B,S,K) @ (N,K).T -> (B,S,N).
      5. Explicit `shape_expr` field on the output decl. Accepted forms:
           "input0.shape"                       → in0.sizes().vec()
           "input0.shape[:-1]"                  → in0.sizes()[:-1]
           "input0.shape[:-1] + input1.shape[-1:]"
           "input0.shape[:-2] + input0.shape[-2:-1] + input1.shape[-1:]"
         shape_expr overrides pattern matching when present (lets users wire
         odd shapes that don't fit 1–4 without hand-maintaining cpp).
    """
    out_shape = list(out_decl.get("shape", []))
    if not out_shape:
        raise ValueError(f"output `{out_decl.get('name')}` has empty shape in op_desc")

    # ------- Pattern 5: explicit shape_expr ----------------------------------
    expr = out_decl.get("shape_expr")
    if expr:
        return _compile_shape_expr(expr, inputs_dsl)

    in0_decl = in_decls[0]
    in0_shape = list(in0_decl.get("shape", []))
    in0_dsl_name = inputs_dsl[0][0]

    # ------- Pattern 1: full equality -----------------------------------------
    if out_shape == in0_shape:
        return f"{in0_dsl_name}.sizes().vec()"
    # ------- Pattern 2: drop last dim -----------------------------------------
    if len(out_shape) + 1 == len(in0_shape) and out_shape == in0_shape[:-1]:
        return (
            f"std::vector<int64_t>("
            f"{in0_dsl_name}.sizes().begin(), "
            f"{in0_dsl_name}.sizes().end() - 1)"
        )

    # Patterns 3-4 need a second input
    if len(in_decls) >= 2 and len(inputs_dsl) >= 2:
        two_input = _infer_two_input_shape_expr(
            out_shape, in0_shape, in0_dsl_name, in_decls, inputs_dsl
        )
        if two_input is not None:
            return two_input

    raise ValueError(
        f"cannot infer output shape for `{out_decl.get('name')}` "
        f"(shape={out_shape}); expected to match one of: "
        f"input[0].shape, input[0].shape[:-1], "
        f"input[0].shape[:-1]+[input[1].shape[-1]] (matmul), "
        f"input[0].shape[:-2]+[input[0].shape[-2],input[1].shape[-1]] (batched matmul), "
        f"input[0].shape[:-1]+[input[1].shape[-2]] (transposed-weight matmul, nn.Linear). "
        f"Inputs: {[list(d.get('shape', [])) for d in in_decls]}. "
        f"To override, add `shape_expr` to this output decl in op_desc.json. "
        "Otherwise hand-maintain cpp."
    )


# ----------------------------------------------------------------------------
# shape_expr DSL — tiny serialisation of slicing/concat for output shape decls
# ----------------------------------------------------------------------------

_SHAPE_TERM_RE = None  # built lazily


def _compile_shape_term(t: str, expr: str, inputs_dsl: List[Tuple[str, str]]) -> str:
    """把 shape_expr 的单个加项编译成返回 std::vector<int64_t> 的 C++ 片段。

    支持 `input0.shape`、`input0.shape[k]`、`input0.shape[a:b]` 三种形态；
    负索引翻译为 .end() + (-k)，非负索引翻译为 .begin() + k。
    """
    m = _SHAPE_TERM_RE.fullmatch(t)
    if not m:
        raise ValueError(
            f"unparseable shape_expr term {t!r} in {expr!r}; "
            "expected forms like `input0.shape`, `input0.shape[:-1]`, "
            "`input1.shape[-1:]`"
        )
    idx = int(m.group("idx"))
    if idx >= len(inputs_dsl):
        raise ValueError(
            f"shape_expr references input{idx} but only "
            f"{len(inputs_dsl)} inputs are defined"
        )
    var = inputs_dsl[idx][0]
    start = m.group("start")
    stop = m.group("stop")
    colon = m.group("colon")

    no_subscript = start is None and stop is None and colon is None
    if no_subscript and not m.group(0).endswith("]"):
        # "input0.shape" — full
        return f"{var}.sizes().vec()"

    # Build [start:stop] using .begin()+s, .end()+e where negative offsets
    # are translated via .end()+(-k). For end-relative indices (negative
    # numbers), we use `.end() + N` (since N is negative). For positive
    # indices we use `.begin() + N`.
    def begin_iter(off):
        if off is None:
            return f"{var}.sizes().begin()"
        n = int(off)
        if n >= 0:
            return f"{var}.sizes().begin() + {n}"
        return f"{var}.sizes().end() + ({n})"

    def end_iter(off):
        if off is None:
            return f"{var}.sizes().end()"
        n = int(off)
        if n >= 0:
            return f"{var}.sizes().begin() + {n}"
        return f"{var}.sizes().end() + ({n})"

    if colon is None:
        # bare integer index: input0.shape[k]  → single-element [k:k+1]
        n = int(start)
        return f"std::vector<int64_t>({begin_iter(n)}, {begin_iter(n)} + 1)"
    else:
        return f"std::vector<int64_t>({begin_iter(start)}, {end_iter(stop)})"


def _compile_shape_expr(expr: str, inputs_dsl: List[Tuple[str, str]]) -> str:
    """Translate an `op_desc.output_shapes[*].shape_expr` string into a C++
    expression returning std::vector<int64_t>.

    Grammar (whitespace-insensitive, terms joined with `+` for concatenation):

      term     := "input<idx>.shape"
                | "input<idx>.shape[<start>:<stop>]"
                | "input<idx>.shape[<start>:]"
                | "input<idx>.shape[:<stop>]"
                | "input<idx>.shape[<idx>:<idx>+1]"   (single dim)
      stop/start may be negative.  idx is an int.

    Each term emits a `__concat_back(vec, in.sizes(), start, stop)` style sub-
    expression. We avoid Python eval entirely — only the regex grammar.

    Examples:
      "input0.shape"
        → in0.sizes().vec()
      "input0.shape[:-1]"
        → std::vector<int64_t>(in0.sizes().begin(), in0.sizes().end() - 1)
      "input0.shape[:-1] + input1.shape[-1:]"
        → builds vec from in0[:-1] then appends in1[-1:]
    """
    global _SHAPE_TERM_RE
    if _SHAPE_TERM_RE is None:
        _SHAPE_TERM_RE = re.compile(
            r"input(?P<idx>\d+)\.shape"
            r"(?:\["
            r"(?P<start>-?\d+)?"
            r"(?:(?P<colon>:)(?P<stop>-?\d+)?)?"
            r"\])?"
        )

    terms = [t.strip() for t in expr.split("+")]
    if not terms:
        raise ValueError(f"empty shape_expr: {expr!r}")

    # Build each term as a C++ snippet returning a temporary std::vector<int64_t>
    snippets: List[str] = []
    for t in terms:
        snippets.append(_compile_shape_term(t, expr, inputs_dsl))

    if len(snippets) == 1:
        return snippets[0]

    # Concatenate: build vec from first snippet, push_back each later.
    body = f"auto __s = {snippets[0]}; "
    for s in snippets[1:]:
        body += f"{{ auto __t = {s}; __s.insert(__s.end(), __t.begin(), __t.end()); }} "
    body += "return __s;"
    return f"[&]{{ {body} }}()"


def _attribute_to_c_value(name: str, val):
    """Convert a Python attribute value to (c_type, c_init_expr_string, is_pybind).

    Returns a 3-tuple ``(c_type, c_init_expr, is_pybind)`` where:
      - ``c_type``      : C type for the scalar (e.g. "double", "int64_t")
      - ``c_init_expr`` : initializer expression for the local variable
                          (or default value string if ``is_pybind`` is True —
                           used for the Python signature default)
      - ``is_pybind``   : if True, this attribute is exposed as a pybind / Python
                          function arg (caller-supplied) instead of being baked
                          as a local C++ variable. Used for runtime-configurable
                          values like epsilon, alpha, slope, etc. The Python
                          signature gets ``def {op}(..., {name}: float = <default>)``
                          and the C++ function takes ``<c_type> {name}`` as a param.

    Recognized string-form escape hatches:

      "@<C-expression>"             → int64_t = <expr>     (existing)
                                        Used for graph-static dim derivations,
                                        e.g. ``"N": "@y.size(-2)"``
      "@f:<C-expression>"           → double  = <expr>     (existing)
                                        Used for host-derived float values,
                                        e.g. ``"inv_h": "@f:1.0 / static_cast<double>(H)"``
                                        for division-free reduction (fm-easyasc pattern).
                                        Note: the expression can reference other Var
                                        names; emission order ensures dim aliases
                                        (M/N/H/D/K) are resolved first.
      "@pybind:<default>"           → double  = pybind arg (new)
                                        Marks attribute as runtime-configurable;
                                        becomes a pybind function arg with the given
                                        default value. ``<default>`` is a Python
                                        float literal (e.g. ``1e-6``, ``0.01``).
                                        Used for eps, alpha, slope, threshold etc.

    Note: `isinstance(True, int)` is True in Python — check bool first.
    """
    if isinstance(val, bool):
        return ("bool", "true" if val else "false", False)
    if isinstance(val, int):
        return ("int64_t", str(val), False)
    if isinstance(val, float):
        return ("double", repr(val), False)  # repr preserves precision (e.g. 1e-06)
    if isinstance(val, str):
        if val.startswith("@pybind:"):
            # Runtime-configurable pybind arg. The value flows in from ModelNew /
            # test_cases instead of being baked. We still need a default for the
            # pybind binding's Python signature.
            prefix_len = len("@pybind:")
            default_str = val[prefix_len:]
            # Validate the default is parseable as a Python float (so we can
            # forward it as the Python default in the pybind binding).
            try:
                float(default_str)
            except ValueError as exc:
                raise ValueError(
                    f"attribute `{name}` uses @pybind:<default>, but default "
                    f"`{default_str}` is not a valid float literal."
                ) from exc
            return ("double", default_str, True)
        if val.startswith("@f:"):
            return ("double", val[3:], False)
        if val.startswith("@"):
            return ("int64_t", val[1:], False)
    raise ValueError(
        f"attribute `{name}` has unsupported Python type "
        f"{type(val).__name__} (value={val!r}); "
        'only bool/int/float/str("@<expr>", "@f:<expr>", "@pybind:<default>") are auto-mapped'
    )


def _classify_scalar_var(v: str, attributes: dict, in0_dsl_name: str, last_dim_var):
    """把单个 Var 归类，返回 (classified 条目, pybind 条目或 None)。

    优先级：op_desc.attributes 的显式声明始终优先于 dim 别名默认值，
    以便 matmul 这类多输入算子可以覆盖默认推导。
    """
    if v in attributes:
        c_type, c_expr, is_pybind = _attribute_to_c_value(v, attributes[v])
        if is_pybind:
            # No local C++ assignment; var becomes a function-signature arg.
            return (v, c_type, None, "attribute_pybind"), (v, c_type, c_expr)
        else:
            return (v, c_type, c_expr, "attribute"), None
    elif DIM_ALIASES.get(v) == "last":
        return (v, "int64_t", f"{in0_dsl_name}.size(-1)", "dim_last"), None
    elif DIM_ALIASES.get(v) == "row":
        if (
            last_dim_var
            and DIM_ALIASES.get(last_dim_var) == "last"
            and last_dim_var not in attributes
        ):
            expr = f"{in0_dsl_name}.numel() / {last_dim_var}"
        else:
            expr = f"{in0_dsl_name}.numel() / {in0_dsl_name}.size(-1)"
        return (v, "int64_t", expr, "dim_row"), None
    else:
        raise ValueError(
            f"scalar `{v}` derivation not supported. "
            f"Either add `{v}` to op_desc.json's `attributes` with a default "
            f'value (e.g. `"attributes": {{"{v}": 1.0e-6}}`) '
            f'or `"attributes": {{"{v}": "@pybind:1.0e-6"}}` for '
            f"runtime-configurable, or rename to one of the recognized "
            f"dim aliases ({sorted(DIM_ALIASES)}), "
            f"or bake it as a Python constant in the DSL kernel body."
        )


def infer_scalar_assignments(
    var_names: List[str],
    inputs_dsl: List[Tuple[str, str]],
    op_desc: dict,
):
    """Return (assignments, call_order) for each Var in DSL.

    Resolution rules (in priority order, applied per Var):

    1. **op_desc.attributes (explicit override)** — if `<var>` appears as a key
       in `op_desc.json["attributes"]`, that value wins regardless of whether
       the name happens to match a dim alias. Value types:
           int   → int64_t  (e.g. {"qmax": 127})
           float → double   (e.g. {"eps": 1e-6})
           bool  → bool     (e.g. {"use_smooth": false})
           str "@<C-expr>"  → int64_t = <C-expr>   (escape hatch for multi-input
                              dim resolution, e.g. {"N": "@y.size(-2)"})

    2. **Dim aliases (fallback)** — for `M`/`N`/`H`/`D`/`K` NOT in attributes:
           N/H/D/K  →  first_input.size(-1)             (int64_t)
           M        →  first_input.numel() / <last_dim> (int64_t)
       Convenient default for single-input vector kernels (norm, quant, reduce).
       For matmul-style ops with multiple inputs, use the explicit override.

    3. Otherwise → ValueError. User must either add the value to op_desc
       attributes or remove the Var (bake as a Python constant in the kernel).

    Returns:
      assignments: list of (var_name, c_type, c_init_expr) in DEPENDENCY order
                   (emit as `{c_type} {name} = {expr};` lines in that order).
      call_order:  list of (var_name, c_type) in DSL declaration order — the
                   order/types passed to aclnn{Camel}CustomGetWorkspaceSize,
                   matching the autogenerated aclnn header signature.
    """
    if not var_names:
        return [], []

    in0_dsl_name = inputs_dsl[0][0]
    attributes = op_desc.get("attributes") or {}

    # Find the "last_dim" variable name if any, so M can refer to it.
    last_dim_var = next(
        (v for v in var_names if DIM_ALIASES.get(v) == "last"),
        None,
    )

    # Classify each Var into one of {attribute, attribute_pybind, dim_last,
    # dim_row, error}.
    # Priority: explicit `op_desc.attributes` always wins, so users can override
    # dim-alias defaults for multi-input ops like matmul.
    classified = []  # list of (var, c_type, expr, kind)
    pybind_attrs = []  # list of (var, c_type, py_default) for pybind args
    for v in var_names:
        entry, pybind = _classify_scalar_var(v, attributes, in0_dsl_name, last_dim_var)
        classified.append(entry)
        if pybind is not None:
            pybind_attrs.append(pybind)

    # Dependency order for emit: dim_last first, then dim_row (depends on last),
    # then attributes. Pybind args have no local init (passed from caller), but
    # we still place them ordered so that derived `@f:` exprs after them can
    # reference their values. This is a stable topo-sort.
    #   - dim_last: independent (input.size(-1))
    #   - attribute_pybind: comes from function arg (no init line emitted)
    #   - attribute: may reference dim_last or pybind_attr by name in @f:/@ exprs
    #   - dim_row: independent (input.numel() / last_dim)
    sort_key = {
        "dim_last": 0,
        "attribute_pybind": 1,
        "attribute": 2,
        "dim_row": 3,
    }
    classified_sorted = sorted(classified, key=lambda e: sort_key[e[3]])
    # pybind_attrs are emitted as function params (not local lines), so they're
    # filtered out of `assignments` here; they're returned separately.
    assignments = [
        (v, ct, ex)
        for v, ct, ex, kind in classified_sorted
        if kind != "attribute_pybind"
    ]

    # Call order: DSL declaration order; types looked up from classification.
    type_lookup = {v: ct for v, ct, _, _ in classified}
    call_order = [(v, type_lookup[v]) for v in var_names]
    return assignments, call_order, pybind_attrs



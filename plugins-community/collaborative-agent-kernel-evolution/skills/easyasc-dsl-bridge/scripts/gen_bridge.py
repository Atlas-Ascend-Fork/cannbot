def _host_cast_extra_bytes(in_pairs, out_pairs, op_desc: dict) -> str:
    """按 op_desc 的代表性 shape 累计 host 侧 cast 的额外 HBM 字节数。

    每张量 = numel × (caller 侧字节 + kernel 侧字节)；返回已格式化的量级串。
    """
    dtype_bytes = {
        "bfloat16": 2,
        "float16": 2,
        "float32": 4,
        "float": 4,
        "int8": 1,
        "int32": 4,
        "int64": 8,
    }

    def _shape_numel(decl):
        shape = decl.get("shape") or []
        if not shape:
            return 0
        # All entries should be ints in op_desc; skip if not.
        try:
            n = 1
            for d in shape:
                n *= int(d)
            return n
        except (TypeError, ValueError):
            return 0

    in_decls_map = {
        d.get("name"): d
        for d in (op_desc.get("shape_info") or {}).get("input_shapes") or []
    }
    out_decls_map = {
        d.get("name"): d
        for d in (op_desc.get("shape_info") or {}).get("output_shapes") or []
    }

    # Per-tensor HBM cost. For each cast'd tensor we incur:
    #   bytes_caller (read by .to(...)) + bytes_kernel (written by .to(...))
    #     + bytes_kernel (read by kernel)
    #     + bytes_kernel (written by kernel)
    # The kernel I/O happens anyway (kernel must read/write GM); the host
    # cast adds: bytes_caller + bytes_kernel for INPUT (read orig, write
    # promoted), and bytes_kernel + bytes_caller for OUTPUT.
    # So host-cast OVERHEAD per tensor = bytes_caller + bytes_kernel.
    # Fm-style kernel-side cast avoids this entirely (0 extra HBM).
    total_extra_bytes = 0
    for n, api, dsl in in_pairs:
        decl = in_decls_map.get(n)
        if decl is None:
            continue
        numel = _shape_numel(decl)
        total_extra_bytes += numel * (dtype_bytes.get(api, 0) + dtype_bytes.get(dsl, 0))
    for n, api, dsl in out_pairs:
        decl = out_decls_map.get(n)
        if decl is None:
            continue
        numel = _shape_numel(decl)
        total_extra_bytes += numel * (dtype_bytes.get(api, 0) + dtype_bytes.get(dsl, 0))

    def _humanize_bytes(b):
        if b <= 0:
            return "<unknown>"
        for unit in ("B", "KB", "MB", "GB"):
            if b < 1024:
                return f"{b:.1f} {unit}"
            b /= 1024
        return f"{b:.1f} TB"

    return _humanize_bytes(total_extra_bytes)


def _estimate_host_cast_overhead(in_pairs, out_pairs, op_desc: dict) -> str:
    """按 op_desc 的代表性 shape 估算 host 侧 cast 的 HBM 开销，返回告警文本。

    每张量的额外开销 = bytes_caller + bytes_kernel；kernel 自身的读写本就
    会发生，不计入。kernel 侧 cast 则完全没有这部分开销。
    """
    # Estimate HBM overhead from op_desc's representative shape.
    # Cost model per cast layer (host-side):
    #   read input @ caller_dtype + write @ kernel_dtype  (= up to 3× orig bytes for bf16→fp32)
    #   read output @ kernel_dtype + write @ caller_dtype (same factor)
    # Compare to fm-style kernel-side cast which has 1× orig bytes I/O.
    est = _host_cast_extra_bytes(in_pairs, out_pairs, op_desc)
    return (
        "\n"
        "  ⚠️  PERFORMANCE WARNING — host-side dtype cast emitted\n"
        "  ──────────────────────────────────────────────────────────\n"
        "  The bridge cpp is inserting a host-side cast layer because the\n"
        "  DSL's GMTensor dtype (from build_codegen_inputs) differs from\n"
        "  the public-facing op_desc dtype. This works correctly, but for\n"
        "  bandwidth-bound ops (most elementwise / norm / activation kernels)\n"
        "  it adds a 3-5× HBM penalty vs. the canonical kernel-side cast\n"
        "  pattern.\n"
        "\n"
        f"  Estimated HBM overhead per call (shape from op_desc): {est}\n"
        "    breakdown: input  bytes_caller + bytes_kernel  (read orig, write promoted)\n"
        "               output bytes_kernel + bytes_caller  (read promoted, write orig)\n"
        "\n"
        "  Fix: switch to the DSL example matching your op_desc dtype.\n"
        "  cake convention is ONE canonical pattern (fp32 compute in UB)\n"
        "  with a per-dtype file instance per category:\n"
        "    elementwise / activation:\n"
        "      • fp32 caller →  leaky_relu.py    (4 fp32 tiles, no cast)\n"
        "      • bf16/fp16   →  mish_bf16.py     (+ 2 lo tiles + cast at boundary)\n"
        "    norm with reduction:\n"
        "      • fp32 caller →  add_rms_norm.py  (all fp32, no cast)\n"
        "      • bf16/fp16   →  rms_norm_bf16.py (+ lo tiles + cast; reduction stays fp32)\n"
        "  All under skills/dsl-baseline-generation-easyasc/references/output_example/.\n"
        "\n"
        '  Note: a unified "one DSL, all dtypes" template doesn\'t work —\n'
        "  easyasc's @kernel() decorator AST-rewrites `if`/`else` to\n"
        "  `with If(cond):` context managers that execute both branches'\n"
        "  Python bodies. So Python-level dtype conditionals can't gate\n"
        "  Tensor() allocation. See SKILL.md 'Dtype path' section.\n"
        "  ──────────────────────────────────────────────────────────\n"
    )


def _detect_dtype_mismatch(in_dsl_dtypes, inputs, op_desc, *, out_dsl_dtypes, outputs):
    mismatch_info = ""
    host_cast_warning = ""  # printed to stderr, with HBM cost estimate
    if in_dsl_dtypes is not None and out_dsl_dtypes is not None:
        in_pairs = [
            (n, api, dsl) for (n, api), dsl in zip(inputs, in_dsl_dtypes) if api != dsl
        ]
        out_pairs = [
            (n, api, dsl)
            for (n, api), dsl in zip(outputs, out_dsl_dtypes)
            if api != dsl
        ]
        if in_pairs or out_pairs:
            mismatch_info = (
                "  dtype-cast layer emitted (DSL/op_desc mismatch):\n"
                + "".join(
                    f"    input  {n}: op_desc {api} → kernel {dsl}\n"
                    for n, api, dsl in in_pairs
                )
                + "".join(
                    f"    output {n}: kernel {dsl} → op_desc {api}\n"
                    for n, api, dsl in out_pairs
                )
            )

            host_cast_warning = _estimate_host_cast_overhead(
                in_pairs, out_pairs, op_desc
            )

    return host_cast_warning, mismatch_info


def _parse_aclnn_for_op(inputs, op_name, *, outputs, scalar_call_order, work_dir):
    try:
        header_path = locate_aclnn_header(work_dir, op_name)
    except FileNotFoundError as exc:
        _ERR.info(
            f"[easyasc-dsl-bridge] ERROR: {exc}\n"
            f"  This bridge requires the aclnn header as ground truth for "
            f"parameter ordering. Run easyasc-codegen (cake stage 5) "
            f"with --build first."
        )
        return 3

    camel_name = _to_camel(op_name + "_custom")
    expected_func = f"aclnn{camel_name}GetWorkspaceSize"
    try:
        header_params = parse_aclnn_header(header_path, expected_func)
        aclnn_call_sequence = build_call_sequence(
            header_params, inputs, outputs, scalar_call_order
        )
    except ValueError as exc:
        _ERR.info(
            f"[easyasc-dsl-bridge] ERROR parsing aclnn header {header_path}: {exc}"
        )
        return 4
    return aclnn_call_sequence, header_path


def _align_scalars_with_header(aclnn_call_sequence, scalar_assignments):
    header_scalar_names = {n for k, n, _ in aclnn_call_sequence if k == "scalar"}
    header_scalar_types = {n: c for k, n, c in aclnn_call_sequence if k == "scalar"}
    filtered_assignments: List[Tuple[str, str, str]] = []
    for name, dsl_c_type, init_expr in scalar_assignments:
        if name not in header_scalar_names:
            continue  # codegen-baked Var, skip
        header_c_type = header_scalar_types[name]
        if header_c_type != dsl_c_type:
            _ERR.info(
                f"[easyasc-dsl-bridge] type override for `{name}`: DSL "
                f"inferred `{dsl_c_type}`, aclnn header says `{header_c_type}` — "
                f"using header type"
            )
        filtered_assignments.append((name, header_c_type, init_expr))
    scalar_assignments = filtered_assignments
    return scalar_assignments


def _write_modelnew_and_report(
    aclnn_call_sequence,
    build_out_dir,
    cpp_path,
    *,
    cpp_text,
    header_path,
    inputs,
    modelnew_path,
    op_name,
    outputs,
    scalar_assignments,
):
    cpp_path.write_text(cpp_text, encoding="utf-8")

    # Generate ModelNew skeleton (only if it doesn't already exist — preserve
    # any agent / human edits that added nn.Parameter mirroring).
    modelnew_was_written = False
    if not modelnew_path.exists():
        modelnew_text = generate_modelnew_skeleton(op_name, inputs, outputs)
        modelnew_path.write_text(modelnew_text, encoding="utf-8")
        modelnew_was_written = True

    # mkdir for the evaluation soft-link target (idempotent — easyasc-codegen
    # also creates this, but we keep it here so the bridge can be re-run
    # standalone if needed).
    build_out_dir.mkdir(parents=True, exist_ok=True)

    _LOG.info(f"[easyasc-dsl-bridge] OK — wrote {cpp_path}")
    if modelnew_was_written:
        _LOG.info(
            f"  ModelNew = {modelnew_path}  (skeleton; edit if Model has nn.Parameter)"
        )
    else:
        _LOG.info(f"  ModelNew = {modelnew_path}  (already exists; preserved)")
    _LOG.info(f"  build_out = {build_out_dir}")
    _LOG.info(f"  aclnn header = {header_path}")
    _LOG.info(f"  inputs  = {[n for n, _ in inputs]}")
    _LOG.info(f"  outputs = {[n for n, _ in outputs]}")
    _LOG.info("  call sequence (from header):")
    for kind, dsl_name, c_type in aclnn_call_sequence:
        _LOG.info(f"    {kind:14s} {dsl_name:16s} {c_type}")
    _LOG.info(f"  scalars (emit order) = {[(n, t) for n, t, _ in scalar_assignments]}")


class _ResolvedPaths(NamedTuple):
    build_out_dir: Path
    cpp_path: Path
    desc_path: Path
    dsl_path: Path
    modelnew_path: Path
    op_name: str
    work_dir: Path


def _resolve_paths_and_load_desc(argv):
    """解析命令行、推导各路径并校验必需文件是否存在。

    成功返回七元组；DSL 或 op_desc 缺失时打印错误并返回 None，
    由调用方转为退出码 1。
    """
    parser = argparse.ArgumentParser(
        description="Generate torch_npu bridge cpp from easyasc DSL signature."
    )
    parser.add_argument("op_name", help="Operator name, e.g. dynamic_quant")
    parser.add_argument(
        "--work-dir",
        default=None,
        help="Directory containing <op>_dsl.py and <op>_op_desc.json. "
        "Defaults to output/<op_name>.",
    )
    args = parser.parse_args(argv)

    op_name = args.op_name
    work_dir = Path(args.work_dir) if args.work_dir else Path("output") / op_name
    work_dir = work_dir.resolve()

    dsl_path = work_dir / f"{op_name}_dsl.py"
    desc_path = work_dir / f"{op_name}_op_desc.json"
    cpp_path = work_dir / f"{op_name}.cpp"
    modelnew_path = work_dir / f"{op_name}_custom.py"
    build_out_dir = work_dir / f"{op_name}Custom" / "build_out"

    if not dsl_path.exists():
        _ERR.info(f"[easyasc-dsl-bridge] ERROR: DSL file not found: {dsl_path}")
        return None
    if not desc_path.exists():
        _ERR.info(f"[easyasc-dsl-bridge] ERROR: op_desc not found: {desc_path}")
        return None
    return _ResolvedPaths(
        build_out_dir, cpp_path, desc_path, dsl_path, modelnew_path, op_name, work_dir
    )


def _report_dtype_notes(host_cast_warning, mismatch_info, op_name):
    """打印 aclnn 接口名，以及 dtype 不一致时的转换说明与开销告警。"""
    _LOG.info(f"  aclnn   = aclnn{_to_camel(op_name + '_custom')}")
    if mismatch_info:
        _LOG.info(mismatch_info[:-1] if mismatch_info.endswith("\n") else mismatch_info)
    if host_cast_warning:
        # WARNING goes to stderr so it's visible even when stdout is captured
        # for parsing. Authors see this immediately after running gen_bridge.
        _ERR.info(
            host_cast_warning[:-1]
            if host_cast_warning.endswith("\n")
            else host_cast_warning
        )


class _DslParts(NamedTuple):
    inputs: List[Tuple[str, str]]
    out_shape_exprs: List[str]
    outputs: List[Tuple[str, str]]
    pybind_attrs: List[Tuple[str, str, str]]
    scalar_assignments: List[Tuple[str, str, str]]
    scalar_call_order: List[str]


class _CallShape(NamedTuple):
    aclnn_call_sequence: List[Tuple[str, str, str]]
    header_path: Path
    in_dsl_dtypes: List[str]
    out_dsl_dtypes: List[str]
    scalar_assignments: List[Tuple[str, str, str]]


def _parse_dsl_and_desc(dsl_path, op_name, op_desc):
    """Derive the IO / shape / scalar parts from the DSL and op_desc.

    Returns None when the DSL cannot be interpreted — an exit-code-2
    condition for the caller.
    """
    try:
        params, var_names, output_names = parse_dsl_signature(
            dsl_path, f"{op_name}_custom"
        )
        inputs, outputs = split_io_tensors(params, output_names, op_desc)

        in_decls = op_desc.get("shape_info", {}).get("input_shapes") or []
        out_decls = op_desc.get("shape_info", {}).get("output_shapes") or []
        out_shape_exprs = [
            infer_output_shape_expr(out_decl, in_decls, inputs)
            for out_decl in out_decls
        ]

        scalar_assignments, scalar_call_order, pybind_attrs = infer_scalar_assignments(
            var_names, inputs, op_desc
        )

    except ValueError as exc:
        _ERR.info(f"[easyasc-dsl-bridge] ERROR: {exc}")
        return None

    return _DslParts(
        inputs=inputs,
        out_shape_exprs=out_shape_exprs,
        outputs=outputs,
        pybind_attrs=pybind_attrs,
        scalar_assignments=scalar_assignments,
        scalar_call_order=scalar_call_order,
    )


def _resolve_call_shape(dsl_path, op_name, work_dir, dsl: _DslParts) -> _CallShape:
    """Parse the aclnn header, align scalars to it, and introspect DSL dtypes."""
    # ── aclnn header parsing (authoritative source for call ordering) ──────
    # The header is emitted by easyasc-codegen at:
    #   {work_dir}/easyasc_workspace/{op_name}_raw/build_out/autogen/aclnn_*.h
    # It must exist; if not, easyasc-codegen hasn't built the .run yet — the
    # cake workflow requires stage 5 (codegen + build) to finish
    # before stage 6 (this bridge) runs.
    aclnn_call_sequence, header_path = _parse_aclnn_for_op(
        dsl.inputs,
        op_name,
        outputs=dsl.outputs,
        scalar_call_order=dsl.scalar_call_order,
        work_dir=work_dir,
    )

    # Filter scalar_assignments down to the Vars that actually appear in the
    # header. Codegen-baked Vars (not in header) are dropped — emitting a C++
    # assignment line for them would be dead code, but harmless.
    scalar_assignments = _align_scalars_with_header(
        aclnn_call_sequence, dsl.scalar_assignments
    )

    # Try to learn the DSL-side kernel dtype for each GMTensor. When the DSL
    # uses (e.g.) fp32 for precision but op_desc declares bf16 for the public
    # API, we need to emit bf16↔fp32 cast layer. If introspection fails
    # (e.g. easyasc not on PYTHONPATH), we silently fall back to the
    # pre-P1.2 behavior — no casts, aclTensor uses op_desc dtype directly.
    in_dsl_dtypes, out_dsl_dtypes = detect_dsl_dtypes(
        dsl_path, n_inputs=len(dsl.inputs), n_outputs=len(dsl.outputs)
    )
    return _CallShape(
        aclnn_call_sequence=aclnn_call_sequence,
        header_path=header_path,
        in_dsl_dtypes=in_dsl_dtypes,
        out_dsl_dtypes=out_dsl_dtypes,
        scalar_assignments=scalar_assignments,
    )


def main(argv: List[str]) -> int:
    resolved = _resolve_paths_and_load_desc(argv)
    if resolved is None:
        return 1
    (build_out_dir, cpp_path, desc_path, dsl_path, modelnew_path, op_name, work_dir) = (
        resolved
    )

    op_desc = json.loads(desc_path.read_text(encoding="utf-8"))

    dsl = _parse_dsl_and_desc(dsl_path, op_name, op_desc)
    if dsl is None:
        return 2

    shape = _resolve_call_shape(dsl_path, op_name, work_dir, dsl)

    host_cast_warning, mismatch_info = _detect_dtype_mismatch(
        shape.in_dsl_dtypes,
        dsl.inputs,
        op_desc,
        out_dsl_dtypes=shape.out_dsl_dtypes,
        outputs=dsl.outputs,
    )

    cpp_text = render_cpp(
        op_name=op_name,
        inputs=dsl.inputs,
        outputs=dsl.outputs,
        scalar_assignments=shape.scalar_assignments,
        aclnn_call_sequence=shape.aclnn_call_sequence,
        out_shape_exprs=dsl.out_shape_exprs,
        in_dsl_dtypes=shape.in_dsl_dtypes,
        out_dsl_dtypes=shape.out_dsl_dtypes,
        pybind_attrs=dsl.pybind_attrs,
    )
    _write_modelnew_and_report(
        shape.aclnn_call_sequence,
        build_out_dir,
        cpp_path,
        cpp_text=cpp_text,
        header_path=shape.header_path,
        inputs=dsl.inputs,
        modelnew_path=modelnew_path,
        op_name=op_name,
        outputs=dsl.outputs,
        scalar_assignments=shape.scalar_assignments,
    )
    _report_dtype_notes(host_cast_warning, mismatch_info, op_name)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))

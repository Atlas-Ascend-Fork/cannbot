def detect_dsl_dtypes(
    dsl_path: Path,
    n_inputs: int,
    n_outputs: int,
):
    """Import the DSL file and inspect ``build_codegen_inputs()`` to learn the
    DSL-side dtype of each GMTensor parameter.

    The DSL kernel signature only declares parameter *types* as ``GMTensor`` —
    not concrete dtypes. The actual element dtype is decided by what
    ``build_codegen_inputs()`` constructs (e.g. ``torch.randn(..., dtype=
    torch.float32)`` → fp32 GMTensor at codegen time → aclnn op registered as
    fp32). When the DSL stays in fp32 for precision but the public
    ``op_desc.json`` declares ``bfloat16`` (the user-facing dtype for the
    ``ModelNew`` call), the bridge cpp needs to insert ``bf16 → fp32`` casts
    on inputs and ``fp32 → bf16`` casts on outputs. This helper supplies the
    DSL dtype so :func:`render_cpp` can emit those casts.

    Returns:
        ``(in_dsl_dtypes, out_dsl_dtypes)`` — two lists of dtype strings
        (``'float32'`` etc.) aligned with the ``inputs`` / ``outputs`` returned
        by :func:`split_io_tensors`. If introspection fails (e.g. easyasc not
        importable because PYTHONPATH is missing), returns ``(None, None)``
        and the caller should fall back to op_desc dtype only (no casts).
    """
    try:
        # Re-use easyasc when it's already on PYTHONPATH. We do NOT want to
        # hard-fail here — gen_bridge can still produce a usable cpp without
        # dtype-mismatch handling for ops where DSL == op_desc dtype.
        import importlib.util

        spec = importlib.util.spec_from_file_location("op_dsl_module", dsl_path)
        if spec is None or spec.loader is None:
            return None, None
        module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(module)
        if not hasattr(module, "build_codegen_inputs"):
            return None, None
        args = module.build_codegen_inputs()
        if not isinstance(args, tuple):
            return None, None
        # args layout: (input_tensors..., output_tensors..., var_scalars...)
        # We trust the caller-supplied n_inputs / n_outputs counts from the
        # DSL AST parse — the GMTensor positions are at the start of the tuple.
        if len(args) < n_inputs + n_outputs:
            return None, None
        n_io = n_inputs + n_outputs
        in_tensors = args[:n_inputs]
        out_tensors = args[n_inputs:n_io]
        in_dsl_dtypes = []
        for t in in_tensors:
            if not hasattr(t, "dtype"):
                return None, None
            in_dsl_dtypes.append(_torch_dtype_to_str(t.dtype))
        out_dsl_dtypes = []
        for t in out_tensors:
            if not hasattr(t, "dtype"):
                return None, None
            out_dsl_dtypes.append(_torch_dtype_to_str(t.dtype))
        return in_dsl_dtypes, out_dsl_dtypes
    except Exception as exc:
        # Silently fall back. The bridge cpp will work as before for ops with
        # matching dtype; only mismatched ops will fail at runtime and the
        # user can manually patch the cpp (the prior workaround).
        _ERR.info(
            f"[easyasc-dsl-bridge] note: could not introspect DSL dtypes "
            f"(reason: {type(exc).__name__}: {exc}); falling back to op_desc "
            f"dtype with no cast layer. If you hit aclnn ret=161001 at "
            f"runtime, set PYTHONPATH=${{EASYASC_DSL_HOME}}:${{PYTHONPATH}} "
            f"before re-running this script."
        )
        return None, None


MODELNEW_TEMPLATE = '''\
import torch
import torch.nn as nn
import torch_npu
import custom_ops_lib


def module_fn({fn_params}) -> {return_type}:
    """Auto-generated module_fn — forwards to the AscendC kernel pybind.

    Var scalars declared in the DSL kernel signature are typically baked into
    the kernel at codegen time and are NOT passed through the pybind. Edit
    this file if your op exposes a runtime Var as a pybind arg.
    """
    return custom_ops_lib.{op_name}_custom({call_args})


class ModelNew(nn.Module):
    """Custom AscendC implementation of {op_camel}.

    AUTO-GENERATED skeleton — passthrough wrapper around the kernel pybind.
    If the original `Model` class has nn.Parameter members (weight / bias /
    learnable scales / ...), edit __init__ here to mirror them — including any
    deterministic `torch.manual_seed(...)` call used by Model — and update
    `forward` to pass those parameters into `fn(...)`.
    """

    def __init__(self):
        super().__init__()

    def forward(self, {forward_params}, fn=module_fn) -> {return_type}:
        return fn({forward_call_args})
'''


def generate_modelnew_skeleton(
    op_name: str,
    inputs: List[Tuple[str, str]],
    outputs: List[Tuple[str, str]],
) -> str:
    """Produce a passthrough `{op_name}_custom.py` (ModelNew wrapper).

    Only the kernel-level GMTensor inputs are surfaced as forward args. Var
    scalars are NOT included — they are normally codegen-baked. Multi-output
    kernels return a tuple.
    """
    if not inputs:
        raise ValueError("cannot generate ModelNew: kernel has no inputs")
    if not outputs:
        raise ValueError("cannot generate ModelNew: kernel has no outputs")

    in_names = [name for name, _ in inputs]
    fn_params = ", ".join(f"{n}: torch.Tensor" for n in in_names)
    forward_params = ", ".join(f"{n}: torch.Tensor" for n in in_names)
    call_args = ", ".join(in_names)
    forward_call_args = call_args
    return_type = (
        "torch.Tensor"
        if len(outputs) == 1
        else (
            "tuple"  # keep simple — the actual Tuple[Tensor,...] form requires extra import
        )
    )

    return MODELNEW_TEMPLATE.format(
        fn_params=fn_params,
        forward_params=forward_params,
        call_args=call_args,
        forward_call_args=forward_call_args,
        return_type=return_type,
        op_name=op_name,
        op_camel=_to_camel(op_name + "_custom"),
    )


def _to_camel(name: str) -> str:
    """Mirror `easyasc/kernelbase/kernelbase.py:_to_camel` — snake_case → CamelCase.

    Unlike ``str.capitalize()``, this preserves *internal* capital letters in each
    underscore-separated piece (e.g. ``RMS``, ``CV``, ``ID``). Matches how easyasc
    itself registers the aclnn op name during codegen:

        >>> _to_camel("dynamic_quant_custom")
        'DynamicQuantCustom'
        >>> _to_camel("AddRMSNorm_custom")
        'AddRMSNormCustom'
        >>> _to_camel("foo_bar")
        'FooBar'
    """
    parts = [p for p in name.split("_") if p]
    if not parts:
        return name
    return "".join(p[:1].upper() + p[1:] for p in parts)


def _match_key(name: str) -> str:
    """Normalize an identifier for header-to-DSL name matching.

    easyasc codegen camelCases DSL Vars into the aclnn signature
    (`negative_slope` -> `negativeSlope`), so comparing plain `.lower()` forms
    never matches any multi-word name: 'negativeslope' != 'negative_slope'.
    The caller then falls through to positional matching and binds the header
    param to whatever DSL name comes first, which is how a scalar ends up
    wired to a dim alias. Dropping underscores on both sides makes the two
    spellings compare equal.
    """
    return name.replace("_", "").lower()


def _camel_to_snake(name: str) -> str:
    """Mirror AscendC build harness's snake-case derivation, identical to
    ``easyasc-codegen/scripts/run_codegen.py::_camel_to_snake``. Used here to
    locate the autogen aclnn header (which is emitted with snake_case filename
    by easyasc-codegen regardless of the kernel function's casing).

        >>> _camel_to_snake("AddRMSNorm_custom")
        'add_rms_norm_custom'
        >>> _camel_to_snake("DynamicQuantCustom")
        'dynamic_quant_custom'
    """
    s = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", name)
    s = re.sub(r"([A-Z])([A-Z][a-z])", r"\1_\2", s)
    return s.lower()



def _render_output_allocations(first_input, out_dsl_dtypes, out_shape_exprs, outputs):
    out_alloc_lines: List[str] = []
    out_effective_names: List[str] = []
    output_post_cast_lines: List[str] = []
    for (out_name, api_dt), dsl_dt, shape_expr in zip(
        outputs, out_dsl_dtypes, out_shape_exprs
    ):
        if api_dt == dsl_dt:
            # Single buffer: caller-visible == kernel buffer
            opts_expr = f"{first_input}.options().dtype({DTYPE_TO_AT_KIND[api_dt]})"
            out_alloc_lines.append(
                f"    at::Tensor {out_name} = at::empty({shape_expr}, {opts_expr});"
            )
            out_effective_names.append(out_name)
        else:
            # Kernel writes into a DSL-dtype buffer; we cast back to caller's
            # actual input dtype (NOT op_desc-baked api_dt) so the same kernel
            # binary serves fp16 / fp32 / bf16 inputs uniformly. The op_desc
            # api_dt is used only to pick the DSL-side kernel dtype above.
            kernel_buf = f"{out_name}_out_dsl"
            opts_expr = f"{first_input}.options().dtype({DTYPE_TO_AT_KIND[dsl_dt]})"
            out_alloc_lines.append(
                f"    at::Tensor {kernel_buf} = at::empty({shape_expr}, {opts_expr});"
            )
            out_effective_names.append(kernel_buf)
            # Post-kernel cast back to caller's input dtype (skip cast if
            # already matches — avoid an unnecessary copy).
            output_post_cast_lines.append(
                f"    at::Tensor {out_name} = "
                f"({kernel_buf}.scalar_type() == {first_input}.scalar_type()) "
                f"? {kernel_buf} : {kernel_buf}.to({first_input}.scalar_type());"
            )
    output_allocations = "\n".join(out_alloc_lines)
    output_post_casts_block = "\n".join(output_post_cast_lines)
    return dsl_dt, out_effective_names, output_allocations, output_post_casts_block


def _render_input_effective_names(in_dsl_dtypes, inputs):
    in_effective_names: List[str] = []
    input_dsl_cast_lines: List[str] = []
    for (name, api_dt), dsl_dt in zip(inputs, in_dsl_dtypes):
        if api_dt == dsl_dt:
            in_effective_names.append(name)
        else:
            cast_name = f"{name}_dsl"
            in_effective_names.append(cast_name)
            at_kind = DTYPE_TO_AT_KIND[dsl_dt]
            input_dsl_cast_lines.append(
                f"    at::Tensor {cast_name} = "
                f"({name}.scalar_type() == {at_kind}) "
                f"? {name} : {name}.to({at_kind});"
            )

    input_dsl_casts_block = "\n".join(input_dsl_cast_lines)
    return dsl_dt, in_effective_names, input_dsl_casts_block, name


def _render_acl_tensor_block(
    aclnn_call_sequence,
    in_dsl_dtypes,
    in_effective_names,
    inputs,
    *,
    out_dsl_dtypes,
    out_effective_names,
    outputs,
):
    acl_create_lines: List[str] = []
    for (name, _api_dt), eff_name, dsl_dt in zip(
        inputs, in_effective_names, in_dsl_dtypes
    ):
        acl_create_lines.append(
            f"    aclTensor *{name}_acl = toAclTensor({eff_name}, {DTYPE_TO_ACL[dsl_dt]});"
        )
    for (name, _api_dt), eff_name, dsl_dt in zip(
        outputs, out_effective_names, out_dsl_dtypes
    ):
        acl_create_lines.append(
            f"    aclTensor *{name}_acl = toAclTensor({eff_name}, {DTYPE_TO_ACL[dsl_dt]});"
        )
    acl_tensor_creates = "\n".join(acl_create_lines)

    # ── exec args list — emit in aclnn header order ──
    # Tensors pass `{name}_acl` (the aclTensor *), scalars pass the variable
    # name as-is (its assignment line emits the value earlier in the body).
    exec_lines: List[str] = []
    indent = "        "
    for kind, dsl_name, _c_type in aclnn_call_sequence:
        if kind in ("input_tensor", "output_tensor"):
            exec_lines.append(f"{indent}{dsl_name}_acl,")
        elif kind == "scalar":
            exec_lines.append(f"{indent}{dsl_name},")
    exec_args = (
        "\n".join(exec_lines) + "\n" + indent
    )  # trailing line for the &workspace_size, &executor

    # ── aclTensor destroys ────────────────────────────────────────────────
    acl_destroy_lines: List[str] = []
    for name, _ in inputs + outputs:
        acl_destroy_lines.append(f"    g_destroy_tensor({name}_acl);")
    acl_tensor_destroys = "\n".join(acl_destroy_lines)
    return acl_tensor_creates, acl_tensor_destroys, exec_args


class _SignatureParts(NamedTuple):
    first_input: str
    get_ws_signature_args: str
    in_dsl_dtypes: List[str]
    input_param_list: str
    out_dsl_dtypes: List[str]
    return_tuple_type: str


def _render_signature_parts(
    aclnn_call_sequence, inputs, outputs, pybind_attrs, *, in_dsl_dtypes, out_dsl_dtypes
):
    if in_dsl_dtypes is None:
        in_dsl_dtypes = [api_dt for _, api_dt in inputs]
    if out_dsl_dtypes is None:
        out_dsl_dtypes = [api_dt for _, api_dt in outputs]

    if len(in_dsl_dtypes) != len(inputs):
        raise ValueError("in_dsl_dtypes length mismatch")
    if len(out_dsl_dtypes) != len(outputs):
        raise ValueError("out_dsl_dtypes length mismatch")

    # ── GetWorkspaceFn typedef ────────────────────────────────────────────
    # Signature order comes directly from the aclnn header (parsed earlier).
    # This is the SINGLE SOURCE OF TRUTH — if easyasc-codegen interleaves
    # scalars between inputs and outputs (or any other layout), we follow
    # whatever it emitted.
    sig_chunks: List[str] = [c_type for _, _, c_type in aclnn_call_sequence]
    get_ws_signature_args = ", ".join(sig_chunks)
    if get_ws_signature_args:
        get_ws_signature_args += ", "

    # ── return type tuple<at::Tensor, at::Tensor, ...>  (or single at::Tensor) ──
    if len(outputs) == 1:
        return_tuple_type = "at::Tensor"
    else:
        return_tuple_type = (
            "std::tuple<" + ", ".join("at::Tensor" for _ in outputs) + ">"
        )

    # ── input parameter list (Python → C++ at::Tensor + optional pybind attrs) ──
    input_param_parts = [f"    const at::Tensor &{name}" for name, _ in inputs]
    for attr_name, attr_c_type, _ in pybind_attrs:
        input_param_parts.append(f"    {attr_c_type} {attr_name}")
    input_param_list = ",\n".join(input_param_parts)

    first_input = inputs[0][0]
    return _SignatureParts(
        first_input,
        get_ws_signature_args,
        in_dsl_dtypes,
        input_param_list,
        out_dsl_dtypes,
        return_tuple_type,
    )


class _CastPybindParts(NamedTuple):
    acl_tensor_creates: str
    acl_tensor_destroys: str
    exec_args: str
    input_dsl_casts_block: str
    output_post_casts_block: str
    pybind_arg_decls: str
    return_stmt: str


def _render_cast_and_pybind_parts(
    aclnn_call_sequence,
    in_dsl_dtypes,
    in_effective_names,
    input_dsl_casts_block,
    *,
    inputs,
    out_dsl_dtypes,
    out_effective_names,
    output_post_casts_block,
    outputs,
    pybind_attrs,
):
    acl_tensor_creates, acl_tensor_destroys, exec_args = _render_acl_tensor_block(
        aclnn_call_sequence,
        in_dsl_dtypes,
        in_effective_names,
        inputs,
        out_dsl_dtypes=out_dsl_dtypes,
        out_effective_names=out_effective_names,
        outputs=outputs,
    )

    # ── return statement ──────────────────────────────────────────────────
    # Single output  →  `return <name>;`         (function returns at::Tensor)
    # Multiple outs  →  `return std::make_tuple(...)` (function returns std::tuple)
    if len(outputs) == 1:
        return_stmt = outputs[0][0]
    else:
        return_stmt = "std::make_tuple(" + ", ".join(n for n, _ in outputs) + ")"

    # ── prefix the function body with input casts (if any) ────────────────
    if input_dsl_casts_block:
        input_dsl_casts_block = (
            "    // bf16/fp32 (or other) cast: caller-visible dtype differs from\n"
            "    // DSL-side kernel dtype (DSL keeps fp32 for precision while the\n"
            "    // ModelNew interface passes bf16, etc.). gen_bridge.py auto-\n"
            "    // detected this via build_codegen_inputs() introspection.\n"
            + input_dsl_casts_block
            + "\n"
        )
    if output_post_casts_block:
        output_post_casts_block = (
            "\n    // Cast outputs back from DSL dtype to caller-visible (op_desc) dtype.\n"
            + output_post_casts_block
        )

    # ── Build pybind arg decls (py::arg("name") = default, ...) ───────────
    # For attributes marked "@pybind:<default>", emit one py::arg(...) per attr
    # so Python callers can pass them as kwargs with defaults preserved.
    pybind_arg_decls = ""
    if pybind_attrs:
        decls = []
        for attr_name, _c_type, py_default in pybind_attrs:
            decls.append(f', py::arg("{attr_name}") = {py_default}')
        # Also need the at::Tensor args (without defaults) as py::arg("name").
        # pybind11 requires consecutive py::arg() for ALL args once you start
        # naming them — so list inputs too.
        named_inputs = "".join(f', py::arg("{n}")' for n, _ in inputs)
        pybind_arg_decls = named_inputs + "".join(decls)
    return _CastPybindParts(
        acl_tensor_creates,
        acl_tensor_destroys,
        exec_args,
        input_dsl_casts_block,
        output_post_casts_block,
        pybind_arg_decls,
        return_stmt,
    )



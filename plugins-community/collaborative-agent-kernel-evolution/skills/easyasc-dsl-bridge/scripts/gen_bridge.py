def locate_aclnn_header(work_dir: Path, op_name: str) -> Path:
    """Find the autogen aclnn header under
    ``work_dir/easyasc_workspace/{op_name}_raw/build_out/autogen/``.

    easyasc-codegen writes the file with a snake_case name derived from the
    kernel function (e.g. ``aclnn_add_rms_norm_custom.h`` for kernel
    ``AddRMSNorm_custom``). We try the expected name first, then glob the
    autogen dir as a fallback (single match required).
    """
    autogen_dir = (
        work_dir / "easyasc_workspace" / f"{op_name}_raw" / "build_out" / "autogen"
    )
    if not autogen_dir.is_dir():
        raise FileNotFoundError(
            f"autogen directory not found: {autogen_dir}. "
            f"Did easyasc-codegen finish building the .run? "
            f"(Run with --build before invoking gen_bridge.py.)"
        )

    expected = autogen_dir / f"aclnn_{_camel_to_snake(op_name + '_custom')}.h"
    if expected.is_file():
        return expected

    hits = sorted(autogen_dir.glob("aclnn_*.h"))
    if len(hits) == 1:
        return hits[0]
    if len(hits) == 0:
        raise FileNotFoundError(
            f"no aclnn_*.h in {autogen_dir}. easyasc-codegen build did not "
            f"complete successfully."
        )
    raise FileNotFoundError(
        f"multiple aclnn_*.h candidates in {autogen_dir}: "
        f"{[p.name for p in hits]}. Expected `{expected.name}` but it is "
        f"missing — fix the kernel name or rebuild."
    )


def _parse_aclnn_param(raw: str, expected_func_name: str) -> Tuple[str, str, str]:
    """把 C 声明里的单个形参解析成 (名称, C 类型, 类别)。

    类别为 tensor / internal / scalar；星号无论贴在类型侧还是名称侧，
    都归入 C 类型。
    """
    # Split off the trailing identifier (param name). The asterisks (if any)
    # may be glued to either side; treat them as part of the C type.
    parts = raw.rsplit(None, 1)
    if len(parts) != 2:
        raise ValueError(f"can't parse param `{raw}` in {expected_func_name} signature")
    c_type_lead, name_part = parts
    ast_match = re.match(r"^(\*+)(.+)$", name_part)
    if ast_match:
        asterisks, name = ast_match.group(1), ast_match.group(2)
        c_type = (c_type_lead + " " + asterisks).strip()
    else:
        name = name_part
        c_type = c_type_lead.strip()

    # Normalize whitespace in the c_type so emitting it later looks clean.
    c_type = re.sub(r"\s+", " ", c_type)

    # Classify.
    if "aclTensor" in c_type:
        kind = "tensor"
    elif name in ("workspaceSize", "executor"):
        kind = "internal"
    else:
        kind = "scalar"
    return name, c_type, kind


def parse_aclnn_header(header_path: Path, expected_func_name: str):
    """Parse the ``aclnn{Op}CustomGetWorkspaceSize`` declaration.

    Returns an ordered list of ``(param_name, c_type, kind)`` tuples where
    ``kind`` is one of:

        "tensor"   — ``const aclTensor *``
        "scalar"   — ``int64_t`` / ``double`` / ``bool`` / ...
        "internal" — trailing ``uint64_t *workspaceSize``,
                     ``aclOpExecutor **executor`` (callers should skip these)

    The ordering is exactly the order in the C declaration — this is the
    authoritative source of truth used to assemble both the function-pointer
    typedef and the runtime call sequence in the bridge cpp.

    Raises ValueError if the function is not found or any param cannot be
    parsed.
    """
    text = header_path.read_text(encoding="utf-8")

    # Find  `aclnnStatus <expected_func_name>(  ...  );`  spanning multiple lines.
    pat = re.compile(
        r"aclnnStatus\s+"
        + re.escape(expected_func_name)
        + r"\s*\(\s*(?P<body>[^)]*?)\s*\)\s*;",
        re.DOTALL,
    )
    m = pat.search(text)
    if not m:
        raise ValueError(
            f"function `{expected_func_name}` not found in {header_path}. "
            f"Is the kernel name registered with easyasc-codegen consistent "
            f"with the bridge's expectation?"
        )

    body = m.group("body")
    raw_params = [p.strip() for p in body.split(",") if p.strip()]
    if not raw_params:
        raise ValueError(
            f"`{expected_func_name}` in {header_path} has empty parameter list"
        )

    parsed: List[Tuple[str, str, str]] = [
        _parse_aclnn_param(raw, expected_func_name) for raw in raw_params
    ]

    # Sanity: the last two must be the workspace + executor internals.
    if not (
        len(parsed) >= 2 and parsed[-2][2] == "internal" and parsed[-1][2] == "internal"
    ):
        raise ValueError(
            f"`{expected_func_name}` does not end with the expected "
            f"`uint64_t *workspaceSize, aclOpExecutor **executor` — got "
            f"trailing params {parsed[-2:]}"
        )

    return parsed


def _match_header_tensor(hname, c_type, by_key, remaining):
    """把头文件里的一个 tensor 形参匹配到 DSL 的输入或输出。

    by_key 为 (输入名映射, 输出名映射)，remaining 为 (未用输入, 未用输出)；
    两个 remaining 列表会被就地消费。返回 (类别, DSL 名, C 类型)。
    """
    dsl_input_by_key, dsl_output_by_key = by_key
    remaining_inputs, remaining_outputs = remaining
    hl = _match_key(hname)
    if hl in dsl_input_by_key and dsl_input_by_key[hl] in remaining_inputs:
        dsl_name = dsl_input_by_key[hl]
        remaining_inputs.remove(dsl_name)
        return "input_tensor", dsl_name, c_type
    elif hl in dsl_output_by_key and dsl_output_by_key[hl] in remaining_outputs:
        dsl_name = dsl_output_by_key[hl]
        remaining_outputs.remove(dsl_name)
        return "output_tensor", dsl_name, c_type
    elif hl == "out" and remaining_outputs:
        dsl_name = remaining_outputs.pop(0)
        return "output_tensor", dsl_name, c_type
    elif remaining_inputs:
        dsl_name = remaining_inputs.pop(0)
        _ERR.info(
            f"[easyasc-dsl-bridge] WARN: header tensor `{hname}` "
            f"matched positionally to DSL input `{dsl_name}` (no name match)"
        )
        return "input_tensor", dsl_name, c_type
    elif remaining_outputs:
        dsl_name = remaining_outputs.pop(0)
        _ERR.info(
            f"[easyasc-dsl-bridge] WARN: header tensor `{hname}` "
            f"matched positionally to DSL output `{dsl_name}` (no name match)"
        )
        return "output_tensor", dsl_name, c_type
    else:
        raise ValueError(
            f"header tensor `{hname}` cannot be matched to any "
            f"remaining DSL tensor (all consumed)"
        )


def _match_header_scalar(hname, c_type, dsl_scalar_by_key, remaining_scalars):
    """把头文件里的一个标量形参匹配到 DSL 的 Var。remaining_scalars 就地消费。"""
    hl = _match_key(hname)
    if hl in dsl_scalar_by_key and dsl_scalar_by_key[hl] in remaining_scalars:
        dsl_name = dsl_scalar_by_key[hl]
        remaining_scalars.remove(dsl_name)
        return "scalar", dsl_name, c_type
    elif remaining_scalars:
        dsl_name = remaining_scalars.pop(0)
        _ERR.info(
            f"[easyasc-dsl-bridge] WARN: header scalar `{hname}` "
            f"matched positionally to DSL Var `{dsl_name}` (no name match)"
        )
        return "scalar", dsl_name, c_type
    else:
        raise ValueError(
            f"header scalar `{hname}` (type {c_type}) cannot be "
            f"matched to any remaining DSL Var. The DSL probably "
            f"declares too few Vars or this scalar is meant to be "
            f"sourced from op_desc.attributes."
        )


def build_call_sequence(
    header_params: List[Tuple[str, str, str]],
    inputs_dsl: List[Tuple[str, str]],
    outputs_dsl: List[Tuple[str, str]],
    scalar_call_order_dsl: List[Tuple[str, str]],
):
    """Walk the header's ordered param list and produce the actual call
    sequence — a list of ``(kind, dsl_name, c_type)`` items in header order.

    Matching strategy (in priority):
      1. Case-insensitive name match against the appropriate DSL group
         (tensors match inputs+outputs; scalars match Vars).
      2. Special case for tensors: header name `out` is paired with the next
         unmatched DSL output (covers ops where DSL uses `y` and codegen
         renames to `out`).
      3. Positional fallback within the remaining DSL group, with a warning.

    Codegen-baked DSL Vars (those not present in the header signature) are
    silently dropped — they don't get an assignment line in the cpp.

    Raises ValueError if a header param cannot be matched.
    """
    dsl_input_by_key = {_match_key(n): n for n, _ in inputs_dsl}
    dsl_output_by_key = {_match_key(n): n for n, _ in outputs_dsl}
    dsl_scalar_by_key = {_match_key(n): n for n, _ in scalar_call_order_dsl}

    remaining_inputs = [n for n, _ in inputs_dsl]
    remaining_outputs = [n for n, _ in outputs_dsl]
    remaining_scalars = [n for n, _ in scalar_call_order_dsl]

    call_sequence: List[Tuple[str, str, str]] = []

    for hname, c_type, kind in header_params:
        if kind == "internal":
            continue
        if kind == "tensor":
            call_sequence.append(
                _match_header_tensor(
                    hname,
                    c_type,
                    (dsl_input_by_key, dsl_output_by_key),
                    (remaining_inputs, remaining_outputs),
                )
            )
        elif kind == "scalar":
            call_sequence.append(
                _match_header_scalar(
                    hname, c_type, dsl_scalar_by_key, remaining_scalars
                )
            )

    if remaining_inputs:
        raise ValueError(
            f"DSL inputs {remaining_inputs} were not referenced by the aclnn "
            f"header — kernel signature drift between DSL and codegen output"
        )
    if remaining_outputs:
        raise ValueError(
            f"DSL outputs {remaining_outputs} were not referenced by the aclnn header"
        )
    if remaining_scalars:
        _ERR.info(
            f"[easyasc-dsl-bridge] note: DSL Vars {remaining_scalars} are "
            f"codegen-baked (not in aclnn signature) — they will NOT appear "
            f"in the bridge cpp call."
        )

    return call_sequence



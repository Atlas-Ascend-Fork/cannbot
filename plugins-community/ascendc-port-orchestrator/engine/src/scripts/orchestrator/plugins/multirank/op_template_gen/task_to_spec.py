"""Static converter: a KernelBench-style task.py + sidecar pair → the
internal generated-form spec.py.

The user-facing multirank input is the SAME task format the single-card
npubench path takes (``Model`` reference implementation +
``get_input_groups()``/``get_init_inputs()``), extended with optional
multi-rank declarations only:

* sidecar case field ``"world_size": N`` — multi-rank case (absent = 1);
* ``get_init_inputs(rank, world_size)`` / ``get_input_groups(rank,
  world_size)`` — keyword-injected per rank subprocess (tasks written for
  the single-card positional form keep working: the converter only checks
  that the parameters are ACCEPTED, never that they exist);
* module flag ``NEEDS_EP_COMM = True`` — the reference needs a live HCCL
  group; ``forward`` then receives a trailing ``comm`` keyword holding the
  extracted hcomm handle (rank/device/world_size attached);
* sidecar case field ``"tolerance": {"atol": A, "rtol": R}`` — spec-level
  precision thresholds for quantized references (spec is global, so every
  case that declares it must declare the SAME value; the canonical judge
  then uses the allclose-style bound instead of the per-dtype default).

The conversion is fully static: the generated spec.py references the task
module verbatim (no rewriting of user code), maps the sidecar data
directly into ``SPEC``, and embeds a sha256 over the frozen task+sidecar
bytes so the golden cache key covers any change to the generator.
Inputs are NOT materialized by the harness (no randn/zeros profiles):
``get_input_groups`` is the single input generator, called per rank at
collection and verification time.
"""

from __future__ import annotations

import hashlib
import json
import re
import shutil
from pathlib import Path

_TASK_STEM = "task"

_SPEC_TEMPLATE = """# GENERATED by task_to_spec from task.py + {sidecar_name} — internal
# representation. Do not edit: regenerate from the user-facing pair instead.
from __future__ import annotations

import sys as _sys
from pathlib import Path as _Path

_HERE = _Path(__file__).resolve().parent
if str(_HERE) not in _sys.path:
    _sys.path.insert(0, str(_HERE))

from {task_stem} import Model, get_input_groups, get_init_inputs  # noqa: E402,F401
try:
    from {task_stem} import NEEDS_EP_COMM  # noqa: E402
except ImportError:
    NEEDS_EP_COMM = False

SPEC = {{
    "op_name": {op!r},
    "input_mode": "task_generated",
    "needs_ep_comm": NEEDS_EP_COMM,
    "inputs": {inputs!r},
    "kernel_input_order": {input_names!r},
    "cases": {cases!r},
    "world_sizes": {world_sizes!r},
    "truth": {truth!r},
    "task_sha256": {digest!r},
{tolerance_line}
}}
"""


class TaskConversionError(ValueError):
    """A user-facing task/sidecar pair cannot be converted statically."""


def discover_sidecar(task_path: Path) -> Path:
    """Resolve the task's single same-stem ``.json``/``.jsonl`` sidecar."""
    task_path = Path(task_path)
    if not task_path.is_file():
        raise TaskConversionError(f"task file not found: {task_path}")
    hits = [
        p
        for suffix in (".json", ".jsonl")
        if (p := task_path.with_suffix(suffix)).is_file()
    ]
    if not hits:
        raise TaskConversionError(
            f"--multirank task requires exactly one same-stem .json or "
            f".jsonl sidecar next to {task_path}"
        )
    if len(hits) > 1:
        raise TaskConversionError(
            f"task has both .json and .jsonl sidecars; keep exactly one "
            f"next to {task_path}"
        )
    return hits[0]


def _load_sidecar_cases(sidecar: Path) -> list[dict]:
    text = sidecar.read_text(encoding="utf-8").strip()
    if not text:
        raise TaskConversionError(f"empty sidecar: {sidecar}")
    if text.startswith("["):
        cases = json.loads(text)
    else:
        cases = [json.loads(line) for line in text.splitlines() if line.strip()]
    if not isinstance(cases, list) or not cases:
        raise TaskConversionError(f"sidecar carries no cases: {sidecar}")
    for i, case in enumerate(cases):
        if not isinstance(case, dict) or not isinstance(case.get("inputs"), list):
            raise TaskConversionError(
                f"sidecar case #{i} must be an object with an inputs list"
            )
    return cases


def _check_generator_signature(task_src: str) -> None:
    """The per-rank keyword injection requires the two generators to ACCEPT
    ``rank``/``world_size`` (positional single-card signatures are fine too
    — static text check, no execution)."""
    for fn in ("get_input_groups", "get_init_inputs"):
        m = re.search(rf"^def {fn}\s*\(([^)]*)\)", task_src, re.MULTILINE)
        if m is None:
            raise TaskConversionError(f"task.py does not define {fn}()")
        params = m.group(1)
        for kw in ("rank", "world_size"):
            if not re.search(rf"\b{kw}\b\s*(?:=|,|\))", params):
                raise TaskConversionError(
                    f"{fn}() must accept the per-rank keyword ``{kw}`` "
                    f"(multi-rank tasks receive rank=..., world_size=...)"
                )


def _content_digest(paths: list[Path]) -> str:
    h = hashlib.sha256()
    for p in paths:
        h.update(str(p.name).encode())
        h.update(p.read_bytes())
    return h.hexdigest()


def _extract_tolerance(cases_raw: list[dict]) -> dict | None:
    """Collect the sidecar's case-declared tolerance into one spec value.

    The spec's ``SPEC['tolerance']`` is global, so every case that declares
    a tolerance must declare the SAME dict (mixed declarations are a
    user-facing ambiguity and fail closed). Accepted shape: a dict with
    non-negative numeric ``atol``/``rtol`` keys (either may be omitted).
    """
    declared: dict | None = None
    for i, raw in enumerate(cases_raw):
        value = raw.get("tolerance")
        if value is None:
            continue
        where = f"sidecar case #{i} ({raw.get('name', f'case{i}')})"
        if not isinstance(value, dict) or not value:
            raise TaskConversionError(
                f"{where}: 'tolerance' must be a non-empty object with "
                f"atol/rtol keys, got {value!r}"
            )
        bad_keys = set(value) - {"atol", "rtol"}
        if bad_keys:
            raise TaskConversionError(
                f"{where}: 'tolerance' has unknown key(s) "
                f"{sorted(bad_keys)}; only atol/rtol are accepted"
            )
        for key, number in value.items():
            if (
                isinstance(number, bool)
                or not isinstance(number, (int, float))
                or number < 0
            ):
                raise TaskConversionError(
                    f"{where}: 'tolerance.{key}' must be a non-negative "
                    f"number, got {number!r}"
                )
        if declared is None:
            declared = dict(value)
        elif value != declared:
            raise TaskConversionError(
                f"{where}: 'tolerance' disagrees with an earlier case "
                f"({value!r} vs {declared!r}); SPEC['tolerance'] is global — "
                f"declare the same value on every case or on none"
            )
    return declared


def convert_task_to_spec(
    task_path: Path,
    *,
    out_dir: Path,
    op: str | None = None,
    truth: str = "npubench",
    tolerance: dict | None = None,
) -> Path:
    """Freeze task+sidecar into ``out_dir`` and generate the spec.py there.

    Returns the generated spec path. The frozen copies keep the cache key
    stable against later edits of the originals.
    """
    task_path = Path(task_path)
    sidecar = discover_sidecar(task_path)
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    task_src = task_path.read_text(encoding="utf-8")
    _check_generator_signature(task_src)
    cases_raw = _load_sidecar_cases(sidecar)
    # The sidecar is the declaration point; the explicit argument stays as a
    # caller-side default for pairs that declare nothing (sidecar wins).
    tolerance = tolerance or _extract_tolerance(cases_raw)

    frozen_task = out_dir / f"{_TASK_STEM}{task_path.suffix or '.py'}"
    frozen_sidecar = out_dir / sidecar.name
    shutil.copy2(task_path, frozen_task)
    shutil.copy2(sidecar, frozen_sidecar)
    digest = _content_digest([frozen_task, frozen_sidecar])

    first_inputs = cases_raw[0]["inputs"]
    input_names = [
        d.get("name")
        for d in first_inputs
        if isinstance(d, dict) and d.get("type") == "tensor"
    ]

    cases = []
    world_sizes: list[int] = []
    for i, raw in enumerate(cases_raw):
        ws = int(raw.get("world_size", 1))
        if ws < 1:
            raise TaskConversionError(f"sidecar case #{i} declares world_size={ws!r}")
        cases.append({"name": raw.get("name", f"case{i}"), "world_size": ws})
        if ws not in world_sizes:
            world_sizes.append(ws)
    world_sizes.sort()

    tolerance_line = ""
    if tolerance:
        tolerance_line = f'    "tolerance": {tolerance!r},'

    spec_path = out_dir / "spec.py"
    spec_path.write_text(
        _SPEC_TEMPLATE.format(
            sidecar_name=frozen_sidecar.name,
            task_stem=_TASK_STEM,
            op=op or task_path.stem,
            inputs=first_inputs,
            input_names=input_names,
            cases=cases,
            world_sizes=world_sizes,
            truth=truth,
            digest=digest,
            tolerance_line=tolerance_line,
        ),
        encoding="utf-8",
    )
    return spec_path


def is_task_form(path: Path) -> bool:
    """Cheap static probe: a task-form file defines get_input_groups and a
    Model class; a derived-form spec defines a SPEC dict.
    """
    try:
        src = Path(path).read_text(encoding="utf-8")
    except OSError:
        return False
    return (
        "def get_input_groups" in src
        and re.search(r"^class Model\b", src, re.MULTILINE) is not None
    )
